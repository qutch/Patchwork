import { useEffect, useMemo, useState } from "react";
import { api, type VersionDetail, type VersionDiff } from "../api";
import { fmtTime } from "../lib/derive";
import { useApp, usePoll } from "../state";
import { Card, CodeBlock, Diff, DiffStat, Empty, PageHead, Pill, Tabs, TestsPill } from "../components/ui";

const FILE_ORDER = ["integration.py", "parsers.py", "adapters.py", "transforms.py", "config.yaml", "spec.yaml", "golden.json", "manifest.json"];
function sortFiles(files: string[]) {
  const rank = (f: string) => {
    const i = FILE_ORDER.indexOf(f);
    return i >= 0 ? i : f.startsWith("tests/") ? 100 : 50;
  };
  return [...files].filter((f) => !f.endsWith("__init__.py")).sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
}

function TestList({ v }: { v: VersionDetail }) {
  if (!v.tests?.length) {
    return (
      <div className="grid gap-2">
        <TestsPill passed={v.tests_passed} summary={v.tests_summary} />
        <pre className="code rounded" style={{ whiteSpace: "pre-wrap" }}>{v.tests_summary ?? "No test summary."}</pre>
      </div>
    );
  }
  const byFile = new Map<string, typeof v.tests>();
  for (const t of v.tests) byFile.set(t.file, [...(byFile.get(t.file) ?? []), t]);
  return (
    <div className="grid gap-3">
      <div className="flex items-center gap-3 flex-wrap">
        <TestsPill passed={v.tests_passed} summary={v.tests_summary} />
        <span className="text-sm text-muted">Generated by the compiler: golden, negative, dedupe, contract and no-AI checks.</span>
      </div>
      <div className="grid gap-3 md:grid-cols-2">
        {[...byFile.entries()].map(([file, tests]) => (
          <div key={file} className="border border-line rounded-md">
            <div className="px-3 py-2 border-b border-line font-mono text-[13px] font-semibold flex justify-between">
              {file}
              <span className="text-muted font-normal">{tests!.filter((t) => t.status === "PASSED").length}/{tests!.length}</span>
            </div>
            <ul className="m-0 p-0 list-none">
              {tests!.map((t) => (
                <li key={t.name} className="px-3 py-1 font-mono text-[12.5px] flex gap-2 items-baseline">
                  <span style={{ color: t.status === "PASSED" ? "var(--ok)" : "var(--bad)" }} className="font-bold">{t.status === "PASSED" ? "✓" : "✗"}</span>
                  <span className="break-all">{t.name}</span>
                </li>
              ))}
            </ul>
          </div>
        ))}
      </div>
    </div>
  );
}

function DiffView({ name, versions }: { name: string; versions: number[] }) {
  const [from, setFrom] = useState(versions.length > 1 ? versions[versions.length - 2] : versions[0]);
  const [to, setTo] = useState(versions[versions.length - 1]);
  const [diff, setDiff] = useState<VersionDiff | null>(null);
  const [err, setErr] = useState<string | null>(null);
  useEffect(() => {
    setDiff(null);
    setErr(null);
    api.diff(name, from, to).then(setDiff, (e) => setErr(String(e.message ?? e)));
  }, [name, from, to]);
  const files = diff ? Object.keys(diff.code_diff) : [];
  const [file, setFile] = useState<string>("spec");
  useEffect(() => setFile("spec"), [from, to]);
  return (
    <div className="grid gap-3">
      <div className="flex items-center gap-2 flex-wrap font-mono text-sm">
        <span className="text-muted">compare</span>
        <select className="input w-auto" value={from} onChange={(e) => setFrom(Number(e.target.value))} aria-label="From version">
          {versions.map((v) => <option key={v} value={v}>v{v}</option>)}
        </select>
        <span>→</span>
        <select className="input w-auto" value={to} onChange={(e) => setTo(Number(e.target.value))} aria-label="To version">
          {versions.map((v) => <option key={v} value={v}>v{v}</option>)}
        </select>
      </div>
      {err && <p className="m-0" style={{ color: "var(--bad)" }}>{err}</p>}
      {diff && (
        <div className="border border-line rounded-md overflow-hidden">
          <div className="px-3 py-2 border-b border-line flex flex-wrap gap-1 items-center">
            <Tabs
              value={file}
              onChange={setFile}
              items={[
                { id: "spec", label: <>spec.yaml <DiffStat text={diff.spec_diff} /></> },
                { id: "patch", label: `JSON Patch (${diff.spec_patch.length})` },
                ...files.map((f) => ({ id: f, label: <>{f} <DiffStat text={diff.code_diff[f]} /></> })),
              ]}
            />
          </div>
          {file === "spec" && <Diff text={diff.spec_diff} maxHeight={560} empty={from === to ? "Same version." : "Specs are identical."} />}
          {file === "patch" &&
            (diff.spec_patch.length ? (
              <pre className="code" style={{ maxHeight: 560 }}>
                {diff.spec_patch.map((op, i) => (
                  <div key={i}>
                    <span style={{ color: op.op === "remove" ? "var(--bad)" : op.op === "add" ? "var(--ok)" : "var(--accent)" }}>{op.op.padEnd(8)}</span>
                    {op.from ? `${op.from} → ` : ""}
                    {op.path}
                    {op.value !== undefined ? `  ${JSON.stringify(op.value)}` : ""}
                  </div>
                ))}
              </pre>
            ) : (
              <div className="p-3 text-sm text-muted">No spec changes.</div>
            ))}
          {file !== "spec" && file !== "patch" && <Diff text={diff.code_diff[file] ?? ""} maxHeight={560} />}
          {files.length === 0 && file === "spec" && from !== to && <div className="px-3 py-2 text-xs text-muted border-t border-line">No generated code changed.</div>}
        </div>
      )}
    </div>
  );
}

export default function IntegrationTab() {
  const { integrationName: name, integrations, act, refresh, go } = useApp();
  const exists = integrations.some((i) => i.name === name);
  const status = usePoll(() => api.integration(name), exists ? 2000 : 0, [name, exists]);
  const [sel, setSel] = useState<number | null>(null);
  const [detail, setDetail] = useState<VersionDetail | null>(null);
  const [view, setView] = useState<"code" | "tests" | "diff">("code");
  const [file, setFile] = useState("integration.py");
  const [busy, setBusy] = useState(false);

  const st = exists ? status.data : null;
  const versions = useMemo(() => (st?.versions ?? []).map((v) => v.version), [st]);
  const active = st?.active_version ?? null;
  const shown = sel ?? active ?? versions.at(-1) ?? null;

  useEffect(() => {
    if (shown == null) return;
    setDetail(null);
    api.version(name, shown).then(setDetail, () => setDetail(null));
  }, [name, shown]);

  const move = async (v: number, kind: "deploy" | "rollback") => {
    setBusy(true);
    await act(() => (kind === "deploy" ? api.deploy(name, v) : api.rollback(name, v)));
    setBusy(false);
    void status.reload();
    refresh();
  };

  if (!exists || !st) {
    return (
      <>
        <PageHead eyebrow="Step 4 · the program" title="Integration" />
        <Empty action={<button className="btn btn-primary" onClick={() => go("record")}>Go to Record</button>}>
          No integration yet. Once the BUILD agent compiles a version it shows up here with its generated code and tests.
        </Empty>
      </>
    );
  }

  const files = detail ? sortFiles(Object.keys(detail.files).concat(detail.files["spec.yaml"] ? [] : ["spec.yaml"])) : [];
  const fileText = detail ? (file === "spec.yaml" ? detail.files["spec.yaml"] ?? detail.spec_yaml : detail.files[file] ?? "") : "";

  return (
    <>
      <PageHead
        eyebrow="Step 4 · the program"
        title="Integration"
        right={<span className="font-mono text-[15px]">{name}</span>}
      >
        Every version is compiled from the spec, immutable, and tested before it can go live. Deploy and roll back only move the active
        pointer.
      </PageHead>

      <div className="grid gap-6 lg:grid-cols-[minmax(0,330px)_minmax(0,1fr)]">
        <Card eyebrow="Versions" title={`${versions.length} version${versions.length === 1 ? "" : "s"}`} bodyClass="">
          <ol className="m-0 p-0 list-none">
            {[...st.versions].reverse().map((v) => {
              const isActive = v.version === active;
              const isSel = v.version === shown;
              return (
                <li
                  key={v.version}
                  className="px-4 py-3 border-b border-line last:border-b-0 grid gap-2 cursor-pointer"
                  style={{ background: isSel ? "var(--accent-soft)" : undefined, boxShadow: isSel ? "inset 3px 0 0 var(--accent)" : undefined }}
                  onClick={() => setSel(v.version)}
                >
                  <div className="flex items-center justify-between gap-2">
                    <span className="display text-[20px] font-extrabold">v{v.version}</span>
                    {isActive && (
                      <span className="pill" style={{ background: "var(--ok)", color: "var(--surface)" }}>● ACTIVE</span>
                    )}
                  </div>
                  <TestsPill passed={v.tests_passed} summary={v.tests_summary} />
                  <div className="font-mono text-xs text-muted">
                    built {fmtTime(v.created_at)}
                    {v.deployed_at && ` · deployed ${fmtTime(v.deployed_at)}`}
                  </div>
                  {!isActive && (
                    <div>
                      {active != null && v.version < active ? (
                        <button className="btn" disabled={busy} onClick={(e) => { e.stopPropagation(); void move(v.version, "rollback"); }}>
                          ↶ Roll back to v{v.version}
                        </button>
                      ) : (
                        <button
                          className="btn btn-gate"
                          disabled={busy || !v.tests_passed}
                          title={v.tests_passed ? "Human approval: make this version live" : "Tests have not passed on this version"}
                          onClick={(e) => { e.stopPropagation(); void move(v.version, "deploy"); }}
                        >
                          ◆ Approve &amp; deploy v{v.version}
                        </button>
                      )}
                    </div>
                  )}
                </li>
              );
            })}
          </ol>
          {st.open_incidents.length > 0 && (
            <div className="px-4 py-3 border-t border-line text-sm" style={{ background: "var(--bad-soft)", color: "var(--bad)" }}>
              {st.open_incidents.length} open incident{st.open_incidents.length === 1 ? "" : "s"}: see Runs.
            </div>
          )}
        </Card>

        <Card
          eyebrow={shown != null ? `v${shown}${shown === active ? " · active" : ""}` : ""}
          title={view === "diff" ? "Spec and code diff" : view === "tests" ? "Test results" : "Generated code"}
          right={
            <Tabs
              value={view}
              onChange={setView}
              items={[
                { id: "code", label: "Code" },
                { id: "tests", label: "Tests" },
                { id: "diff", label: "Diff" },
              ]}
            />
          }
          bodyClass={view === "code" ? "" : "card-b"}
        >
          {view === "code" &&
            (detail ? (
              <>
                <div className="px-3 py-2 border-b border-line flex flex-wrap gap-1">
                  <Tabs value={file} onChange={setFile} items={files.map((f) => ({ id: f, label: f }))} />
                </div>
                <div className="px-4 py-1.5 border-b border-line font-mono text-xs text-muted flex justify-between gap-2 flex-wrap">
                  <span>workspace/integrations/{name}/v{detail.version}/{file}</span>
                  <span>{file === "transforms.py" ? "agent-written (custom: functions)" : file === "spec.yaml" ? "agent-written spec" : "generated by the compiler"}</span>
                </div>
                <CodeBlock text={fileText} maxHeight={620} />
              </>
            ) : (
              <div className="p-4 text-muted">Loading…</div>
            ))}
          {view === "tests" && (detail ? <TestList v={detail} /> : <p className="m-0 text-muted">Loading…</p>)}
          {view === "diff" && (versions.length ? <DiffView key={versions.length} name={name} versions={versions} /> : null)}
        </Card>
      </div>

      {st.recent_runs.length > 0 && (
        <Card eyebrow="Recent runs" title="On this integration" bodyClass="overflow-x-auto">
          <table className="tbl">
            <thead>
              <tr><th>Run</th><th>Version</th><th>Mode</th><th>Status</th><th>Counts</th><th>LLM calls</th></tr>
            </thead>
            <tbody>
              {st.recent_runs.map((r) => (
                <tr key={r.id}>
                  <td className="font-mono">#{r.id}</td>
                  <td className="font-mono">v{r.version}</td>
                  <td>{r.dry_run ? "dry run" : "live"}</td>
                  <td><Pill k={r.status === "completed" ? "success" : r.status === "running" ? "duplicate" : "quarantined"}>{r.status}</Pill></td>
                  <td className="font-mono text-xs">{Object.entries(r.counts).filter(([k]) => !k.includes(":")).map(([k, n]) => `${k} ${n}`).join(" · ") || "—"}</td>
                  <td className="font-mono font-semibold" style={{ color: "var(--ok)" }}>{r.llm_calls}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </Card>
      )}
    </>
  );
}
