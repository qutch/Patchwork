    def diff_openapi() -> str:
        """Diff the destination contract the active version was compiled against (old) with the live one
        (new) for the sink call (an API's OpenAPI, or a form's synthesised contract), and pair
        removed/added properties into likely renames. For forms it also returns `patch_hint` (the JSON
        Patch `move` ops for the renames) and asks only when a pairing is not unique."""
        inc = Store().incident(int(ctx.incident_id or 0)) if ctx.incident_id else None
        spec = ctx.spec_dict()
        method, path = sink_call(spec)
        values = sink_values(spec)
        is_form = is_label_keyed(spec)  # form or Airtable: label-keyed, the same repair path (V14)
        what_gone = {"airtable": "Airtable field", "sqlite": "SQLite column"}.get(sink_kind(spec))
        if inc and inc.get("old_openapi") and inc.get("new_openapi"):
            old_doc, new_doc = inc["old_openapi"], inc["new_openapi"]
        else:
            active = Store().active_version(ctx.name)
            old_doc = json.loads((workspace_dir() / "integrations" / ctx.name / f"v{active}" / "contract" / "openapi.json").read_text())
            new_doc = ctx.fetch_contract(spec) if is_form else httpx.get(
                ctx.sink_base() + "/openapi.json", timeout=10, headers=ctx.auth_headers("sink")).json()
        d = diff_request_schemas(old_doc, new_doc, method, path, values)
        d["current_sink_fields" if is_form else "current_sink_body"] = values
        route_by = (spec.get("extract") or {}).get("route_by")
        if route_by:
            routed = sorted({str(p.get("match", {}).get(route_by)) for p in spec["extract"]["parsers"]})
            d["routed_values"] = {route_by: routed}
        dest = (new_doc.get("info") or {}).get("title") or "The destination"
        props = _resolve(new_doc, request_schema(new_doc, method, path) or {}).get("properties", {})
        d["suggested_questions"] = []
        if is_form:
            base = sink_values_path(spec)
            d["patch_hint"] = [{"op": "move", "from": f"{base}/{_ptr(old)}", "path": f"{base}/{_ptr(new)}"}
                               for old, new in d["likely_renames"].items() if old in values]
            unpaired_old = [r for r in d["removed"] if r not in d["likely_renames"] and r in values]
            unpaired_new = [a for a in d["added"] if a not in d["likely_renames"].values()]
            for r in unpaired_old:
                question = (f"The {what_gone} {r!r} is gone from the table. Which {what_gone.split()[-1]} replaces it?"
                            if what_gone else f"The form question {r!r} is gone. Which new question replaces it?")
                d["suggested_questions"].append({"field": r, "question": question,
                                                 "options": unpaired_new + ["None: stop sending it"]})
            for field in d["new_required_unmapped"]:
                if not unpaired_old:
                    d["suggested_questions"].append({"field": field, "options": [],
                                                     "question": f"The form now requires {field!r}. What value should it get?"})
            return json.dumps(d, indent=1)
        for field in d["new_required_unmapped"]:
            enum = _resolve(new_doc, props.get(field, {})).get("enum")
            if enum:
                d["suggested_questions"].append({
                    "field": field,
                    "question": f"{dest} now requires {field}. Always {enum[0]}, or by supplier?",
                    "options": [f"Always {enum[0]}", "By supplier (tell me which " + field.removesuffix("_id") + " for each supplier)"]})
            else:
                d["suggested_questions"].append({"field": field, "question": f"{dest} now requires {field}. What value should it get?",
                                                 "options": []})
        return json.dumps(d, indent=1)

    def migrate_golden_examples() -> str:
        """After patching sink.body for a new destination contract, rewrite every golden example's
        expected body to the new shape: values fed by the same extracted field are carried over from the
        old expected body; new fields (const, lookup on record.*) are computed from the patched spec."""
        path = ctx.wd / "examples.yaml"
        if not path.exists():
            return "ERROR: no examples.yaml"
        active = ctx.active_spec_text()
        if active is None:
            return "ERROR: no active version to migrate from"
        old_body = sink_values(_yload(active))
        new_spec = ctx.spec_dict()
        new_body = sink_values(new_spec)
        as_text = sink_kind(new_spec) == "form"  # values sent to a form are strings (V5)
        typed_props: dict = {}
        typing = _typing_module(sink_kind(new_spec))
        if typing is not None:  # Airtable / SQLite values are typed per the table's fields (V14, V16)
            properties = typing.properties
            inc = Store().incident(int(ctx.incident_id)) if ctx.incident_id else None
            try:
                doc = (inc or {}).get("new_openapi") or ctx.fetch_contract(new_spec)
                typed_props = properties(doc)
            except Exception:  # noqa: BLE001 - untyped goldens fail the compile's contract test, said there
                typed_props = {}
        by_field = {vs["from"]: k for k, vs in old_body.items() if "from" in vs and "transform" not in vs}
        by_source = {source_key(vs): k for k, vs in old_body.items()}  # the same source under a new name (a rename)
        examples = _yload(path.read_text()) or []
        changed, problems = 0, []
        nested = not is_label_keyed(new_spec)  # an API body: compare by dotted path, write it nested again
        for ex in examples:
            body = ex.get("expect", {}).get("body")
            if body is None:
                continue
            flat = body_to_dotted(body) if nested else body
            out = {}
            for k, vs in new_body.items():
                if by_source.get(source_key(vs)) in flat:
                    out[k] = flat[by_source[source_key(vs)]]
                elif "from" in vs and "transform" not in vs and vs["from"] in by_field and by_field[vs["from"]] in flat:
                    out[k] = flat[by_field[vs["from"]]]
                else:
                    try:
                        out[k] = eval_value(vs, {}, ex["record"])
                        if as_text and out[k] is not None:
                            out[k] = str(out[k])
                        elif typed_props and out[k] not in (None, ""):
                            out[k] = typing.convert_values(typed_props, {k: out[k]}, drop_empty=False)[k]
                    except (Quarantine, KeyError, ValueError, TypeError) as e:
                        problems.append(f"{ex['name']}.{k}: {e}")
            if nested:
                out = dotted_to_body(out)
            if out != body:
                ex["expect"]["body"] = out
                changed += 1
        if problems:
            return "REFUSED (examples unchanged): " + "; ".join(problems[:5])
        path.write_text(_ydump(examples, sort_keys=False, width=200))
        sample = next((e["expect"]["body"] for e in examples if "body" in e.get("expect", {})), None)
        return f"rewrote {changed} expected bodies; e.g. {json.dumps(sample)}"

    def _is_placeholder_option(opt: object) -> bool:
        text = re.sub(r"[\s,$€£¥]", "", str(opt))
        if not text:
            return True
        try:
            return float(text) == 0
        except ValueError:
            return False

    def _placeholder_refusal(dest_field: str, options: list[str] | None) -> str | None:
        """Code check: options the AI offers for a number or required destination field must not be empty or 0."""
        if not dest_field or not options or not ctx.examples_mode():
            return None
        try:
            info = examples_dest_fields(ctx.examples_candidates() or {}, ctx.dest_contract()).get(str(dest_field))
        except Exception:  # noqa: BLE001 - unknown destination: behave as before
            return None
        if not info or not (info.get("required") or info.get("type") in ("number", "integer")):
            return None
        bad = [o for o in options if _is_placeholder_option(o)]
        if not bad:
            return None
        return (f"REFUSED: option(s) {[str(o) for o in bad]} would write a placeholder (empty or 0) into "
                f"{dest_field!r}, a number or required field, on every row. Offer real values seen on the pages, "
                "or an option such as 'Leave it for me to fill in at review'. Nothing was asked.")

    def ask_user(question: str, options: list[str] | None = None, dest_field: str = "") -> str:
        """Ask the human one short question (with 2-3 options) and wait for the answer. Use it to
        confirm inferred assumptions and for values that cannot be derived from the data. In TEACH from
        example pages, name the destination field the question is about in `dest_field`: a constant for
        that field equal to the answer then counts as the person's choice."""
        refused = _placeholder_refusal(dest_field, options)
        if refused:
            return refused
        answer = ctx.interrupt("ask_user", question=question, options=list(options or []))
        if dest_field:
            ctx.answers[str(dest_field)] = str(answer.get("answer", ""))
        return f"user answered: {answer.get('answer', '')}"

