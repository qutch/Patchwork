def sink_call(spec: dict) -> tuple[str, str]:
    """(method, path) of the sink call in its contract document. Form sinks are `POST /form` (V6), Airtable
    sinks `POST /records` (V14), SQLite sinks `POST /rows` (V16)."""
    sink = spec.get("sink") or {}
