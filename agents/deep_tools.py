"""Tools for the deep agent. Every guardrail lives here, in code, not in a prompt:

- no tool can write to the live sink (dry runs go to staging; staging may never equal live)
- `compile_spec` refuses invalid specs; REPAIR gets at most 3 compile attempts, then escalates via ask_user
- `request_deploy` refuses unless the full suite passed on that exact version
- `propose_spec_patch` is a JSON Patch on the spec only; runtime code is always regenerated by the compiler
- the filesystem the agent sees is `workspace/integrations/<name>/work` (permissions in agents.deep
  only allow writing spec.yaml, examples.yaml and transforms.py there)

Tools are plain closures over a `ToolContext` (one per agent thread). They return short strings for the
model; failures start with ERROR or REFUSED so the event mapper can mark them not-ok.
"""

