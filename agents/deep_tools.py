def run_parser(parser: dict, text_field: str, record: dict, html_field: str | None = None) -> dict:
    fields = {}
    text = record.get(text_field) or ""
    for fname, f in parser["fields"].items():
        where = f"{parser.get('id', 'parser')}.{fname}"
        if f.get("css") is not None or f.get("jsonld") is not None:  # page extractors (V3), same helpers as runs
            fields[fname] = learn.extract_field(f, record, where, html_field or "html", text_field)
            continue
        if f.get("combine") == "product" and f.get("regex") is not None:
            fields[fname] = extract_product(text, re.compile(f["regex"]), f.get("cast", "int"), where)
            continue
        if f.get("regex") is not None:
            raw = extract_regex(text, re.compile(f["regex"]), where)
        elif f.get("between") is not None:
            raw = extract_between(text, f["between"][0], f["between"][1], where)
        elif f.get("json_path") is not None:
            raw = extract_json_path(record, f["json_path"], where)
        else:
            raise Quarantine("PARSE_NO_MATCH", f"{where}: no extract method")
        fields[fname] = cast(raw, f.get("cast", "str"), where)
    return fields


def _matches(match: dict, record: dict) -> bool:
    return match_rank({k: str(v) for k, v in (match or {}).items()}, record) > 0


def eval_value(vs: dict, fields: dict, record: dict) -> Any:
    """Evaluate a spec value source the way generated code does (used to migrate golden bodies)."""
    def ref(r: str) -> Any:
        return record[r.removeprefix("record.")] if r.startswith("record.") else fields[r]
    if "template" in vs:
        return re.sub(r"\{([A-Za-z_][A-Za-z0-9_.]*)\}", lambda m: str(ref(m.group(1))), vs["template"])
    if vs.get("transform"):
        name = vs["transform"]
        if name.startswith("custom:"):
            raise ValueError("custom transforms cannot be evaluated here")
        return getattr(T, name)(ref(vs["from"]), **(vs.get("args") or {}))
    if "from" in vs:
        return ref(vs["from"])
    return vs.get("const")


def lint_spec(spec: dict) -> list[str]:
    """Checks the schema can't express: lookup tables must cover every routed value, and the staging
    sink must never be the live sink."""
    problems = []
    sink = spec.get("sink", {})
    if sink.get("staging_base_url") and sink.get("staging_base_url", "").rstrip("/") == sink.get("base_url", "").rstrip("/"):
        problems.append("sink.staging_base_url must not equal sink.base_url (agents never write to live)")
    route_by = spec.get("extract", {}).get("route_by")
    routed = {str(p.get("match", {}).get(route_by)) for p in spec.get("extract", {}).get("parsers", [])
              if p.get("match", {}).get(route_by) is not None}
    for key, vs in (sink_values(spec) or {}).items():
        if vs.get("transform") == "lookup" and vs.get("from") == f"record.{route_by}":
            table = (vs.get("args") or {}).get("table") or {}
            missing = sorted(routed - set(map(str, table)))
            if missing and (vs.get("args") or {}).get("default") is None:
                problems.append(f"sink.body.{key}: lookup table keys {sorted(table)} do not cover routed "
                                f"{route_by} values {missing}; use the exact values, e.g. {sorted(routed)}")
    return problems


def _ptr(key: str) -> str:
    """JSON Pointer escaping for one key (form labels may contain '/' or '~')."""
    return key.replace("~", "~0").replace("/", "~1")


def _short(obj: Any, n: int = 900) -> str:
    s = obj if isinstance(obj, str) else json.dumps(obj, default=str)
    return s if len(s) <= n else s[:n] + f"… (+{len(s) - n} chars)"


def _port_plus_one(url: str) -> str:
    p = urlparse(url)
    if p.port:
        return urlunparse(p._replace(netloc=f"{p.hostname}:{p.port + 1}"))
    return url


