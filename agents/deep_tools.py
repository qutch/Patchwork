def summarize_recording(rec: dict) -> str:
    lines = [f"intent: {rec.get('intent')}", f"allowlist: {rec.get('allowlist')}", f"events: {len(rec['events'])}"]
    for e in rec["events"]:
        typ = e.get("type")
        if typ == "framenavigated":
            lines.append(f"- navigate {e.get('url')} ({e.get('title')})")
        elif typ == "net":
            body = e.get("req") if e.get("method") in ("POST", "PUT", "PATCH") else None
            resp = e.get("resp")
            n = f"{len(resp)} items" if isinstance(resp, list) else "1 object"
            lines.append(f"- {e.get('method')} {e.get('url')} -> {e.get('status')}"
                         + (f" body={json.dumps(body)}" if body is not None else f" ({n})"))
        else:
            el = e.get("el") or {}
            label = el.get("label") or el.get("name") or el.get("testid") or el.get("css")
            val = e.get("value", e.get("text"))
            lines.append(f"- {typ} on {label!r}" + (f" value={val!r}" if val is not None else "")
                         + (f" (near {el.get('nearby')!r})" if el.get("nearby") else ""))
    return "\n".join(lines)


def summarize_openapi(doc: dict) -> str:
    out = []
    for path, ops_ in sorted(doc.get("paths", {}).items()):
        for method, op in ops_.items():
            line = f"{method.upper()} {path}"
            params = [p["name"] for p in op.get("parameters", []) if p.get("in") == "query"]
            if params:
                line += f" query={params}"
            schema = request_schema(doc, method, path)
            if schema:
                line += " body=" + json.dumps(_flatten_schema(doc, schema))
            out.append(line)
    return "\n".join(out)


def _resolve(doc: dict, schema: dict) -> dict:
    while isinstance(schema, dict) and "$ref" in schema:
        node: Any = doc
        for part in schema["$ref"][2:].split("/"):
            node = node.get(part, {})
        schema = node
    return schema or {}


def _flatten_schema(doc: dict, schema: dict) -> dict:
    schema = _resolve(doc, schema)
    props = {}
    for k, v in schema.get("properties", {}).items():
        v = _resolve(doc, v)
        desc = v.get("type", "any")
        if "enum" in v:
            desc += f" enum={v['enum']}"
        if "exclusiveMinimum" in v:
            desc += f" >{v['exclusiveMinimum']:g}"
        props[k] = desc
    return {"properties": props, "required": schema.get("required", []),
            **({"additionalProperties": False} if schema.get("additionalProperties") is False else {})}


def diff_request_schemas(old_doc: dict, new_doc: dict, method: str, path: str,
                         body_map: dict[str, dict] | None = None) -> dict:
    """Compare the request body schema of one operation and pair removed/added properties into
    likely renames: by name similarity first, then by matching the extracted field that fed the old
    property, then by unique type (enum-ness must agree)."""
    old = _flatten_schema(old_doc, request_schema(old_doc, method, path) or {})
    new = _flatten_schema(new_doc, request_schema(new_doc, method, path) or {})
    removed = {k: v for k, v in old["properties"].items() if k not in new["properties"]}
    added = {k: v for k, v in new["properties"].items() if k not in old["properties"]}
    body_map = body_map or {}
    renames: dict[str, str] = {}

    def base_type(d: str) -> tuple[str, bool]:
        return d.split()[0], "enum=" in d

    for r in list(removed):
        best = max(added, key=lambda a: difflib.SequenceMatcher(None, r, a).ratio(), default=None)
        if best and best not in renames.values() and (
                difflib.SequenceMatcher(None, r, best).ratio() >= 0.6 or best.startswith(r) or r.startswith(best)) \
                and base_type(removed[r]) == base_type(added[best]):
            renames[r] = best
    for r in removed:
        if r in renames:
            continue
        src = (body_map.get(r) or {}).get("from")
        if src and src in added and src not in renames.values():
            renames[r] = src
    for r in removed:
        if r in renames:
            continue
        same = [a for a in added if a not in renames.values() and base_type(added[a]) == base_type(removed[r])]
        if len(same) == 1:
            renames[r] = same[0]
    new_required = {a: added[a] for a in added if a not in renames.values() and a in new["required"]}
    return {"operation": f"{method} {path}", "removed": removed, "added": added,
            "likely_renames": renames, "new_required_unmapped": new_required,
            "old_required": old["required"], "new_required": new["required"]}


