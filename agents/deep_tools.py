def candidates_for(recording_id: str) -> dict:
    """workspace candidates.json -> matcher.match (if the capture workstream's matcher is present) ->
    the hand-made fixture (only for the fixture recording)."""
    path = workspace_dir() / "recordings" / recording_id / "candidates.json"
    if path.exists():
        return json.loads(path.read_text())
    if recording_id == JOBS_RECORDING:  # W2's fixture recording, else the agents' V11 stand-in
        own = FIXTURES / "recording_jobs" / "candidates.json"
        return json.loads((own if own.exists() else FIXTURES / "agent_candidates_jobs.json").read_text())
    try:
        from matcher import match  # type: ignore[import-not-found]
    except ImportError:
        match = None
    if match is not None:
        try:
            return match(load_recording(recording_id))
        except Exception:  # noqa: BLE001 - fall through to the fixture for the fixture recording
            if recording_id != "fixture":
                raise
    if recording_id == "fixture":
        return json.loads((FIXTURES / "agent_candidates.json").read_text())
    raise FileNotFoundError(f"no candidates for recording {recording_id} (no candidates.json and no matcher)")


def is_page_candidates(c: dict) -> bool:
    return (c.get("source") or {}).get("kind") == "page" and (c.get("sink") or {}).get("kind") == "form"


def intent_slug(intent: str, max_len: int = 40) -> str:
    """`Track product prices` -> `track_product_prices` (an integration name, contracts V15 item 6): lowercase
    words joined by `_`, at most `max_len` characters (cut at a word), starting with a letter. "" if no words."""
    words = re.findall(r"[a-z0-9]+", (intent or "").lower())
    out = ""
    for w in words:
        nxt = f"{out}_{w}" if out else w
        if len(nxt) > max_len:
            break
        out = nxt
    if not out and words:
        out = words[0][:max_len]
    if out and not out[0].isalpha():
        out = ("p_" + out)[:max_len].rstrip("_")
    return out


def default_build_name(recording_id: str, fallback: str) -> str:
    """BUILD without a name (contracts V9, V15 item 6): the fixture job recording builds `jobs_to_tracker`; any
    other page->form recording builds a slug of its intent (`Track product prices` -> `track_product_prices`);
    other recordings the v1 default."""
    from agents.interface import DEFAULT_PAGE_INTEGRATION
    try:
        c = candidates_for(recording_id)
    except Exception:  # noqa: BLE001 - no candidates yet: the interpreter will report it
        return fallback
    if not is_page_candidates(c) and not is_examples_candidates(c):
        return fallback
    if recording_id == JOBS_RECORDING:
        return DEFAULT_PAGE_INTEGRATION
    intent = c.get("intent") or ""
    if not intent:
        try:
            intent = load_recording(recording_id).get("intent") or ""
        except Exception:  # noqa: BLE001
            intent = ""
    return intent_slug(intent) or DEFAULT_PAGE_INTEGRATION


def snapshot_html(recording_id: str, snapshot: str) -> str:
    """The source page saved at copy time (V11 `snapshots/<n>.html`, relative to the recording dir)."""
    for root in (workspace_dir() / "recordings" / recording_id, FIXTURES / "recording_jobs", FIXTURES):
        p = root / snapshot
        if p.is_file():
            return p.read_text()
    raise FileNotFoundError(f"snapshot {snapshot} of recording {recording_id} not found")


_FIELD_ALIASES = {"job title": "title", "title": "title", "position": "title", "role": "title",
                  "company": "company", "company name": "company", "employer": "company", "organization": "company"}


def _field_name(label: str) -> str:
    key = " ".join(label.lower().replace("*", "").split())
    return _FIELD_ALIASES.get(key) or (re.sub(r"[^a-z0-9]+", "_", key).strip("_") or "field")


def site_parser_id(site: str) -> str:
    """jobs.lever.co -> lever, job-boards.greenhouse.io -> greenhouse, careers.airbnb.com -> airbnb."""
    parts = [p for p in (site or "").lower().split(".") if p]
    name = parts[-2] if len(parts) >= 2 else (parts[0] if parts else "page")
    name = re.sub(r"[^a-z0-9]+", "_", name).strip("_") or "page"
    return name if name[0].isalpha() else f"p_{name}"


def _extractor_from_mapping(m: dict) -> dict | None:
    if m.get("kind") == "css" and m.get("css"):
        f = {"css": m["css"]}
    elif m.get("kind") == "jsonld" and m.get("jsonld"):
        f = {"jsonld": m["jsonld"], **({"jsonld_type": m["jsonld_type"]} if m.get("jsonld_type") else {})}
    else:  # copied text without a selector: fall back to a recorded alternative
        alt = next((a for a in m.get("alternatives") or [] if isinstance(a, dict) and (a.get("css") or a.get("jsonld"))), None)
        if alt is None:
            return None
        f = {k: alt[k] for k in ("css", "attr", "jsonld", "jsonld_type", "regex") if alt.get(k)}
        return f
    for k in ("attr", "regex"):
        if m.get(k):
            f[k] = m[k]
    return f


def draft_page_spec(c: dict, *, name: str, thread_id: str, html: str,
                    airtable: dict | None = None, record: dict | None = None, contract: dict | None = None,
                    kinds: dict[str, dict] | None = None) -> tuple[dict, list[dict], list[str]]:
    """V11 page->form candidates -> a V7/V5 spec with one taught parser, plus one golden example built from
    the snapshot (expected values are the recorded ones, independent of the parser). Returns
    (spec, examples, problems).

    `airtable` (V14 retarget): {base_id, table, credential, fields: {form label: Airtable field name or None},
    contract}: the sink becomes that table, each label keyed by its field name; a None drops the label (a
    person chose to skip it). Golden values are typed per the table's fields.

    TEACH from examples (`c.teach_mode == "examples"`, the mappings come from `propose_mapping`): a mapping may
    name its integration `field`; the sink is the draft's destination (`c.sink`, any kind; API bodies nested
    from dotted paths); `kinds` ({integration field: {type, values?}}) adds each field's type rule; the golden
    example is `record` (the example page as stored) with values typed per `contract`."""
    src, sink = c["source"], c["sink"]
    examples_mode = is_examples_candidates(c)
    site = src.get("site") or ""
    fields, form_fields, assumptions, problems = {}, {}, [], []
    record_values: dict[str, str] = {}
    by_label = {m["dest_field"]: m for m in c.get("mappings") or []}
    labels = list(sink.get("labels") or by_label)
    for label in labels:
        m = by_label.get(label)
        if m is None:
            continue
        kind = m.get("kind")
        if kind == "record" and str(m.get("from", "")).startswith("record."):
            form_fields[label] = {"from": m["from"]}
            record_values[label] = m["from"]
            assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "observed",
                                "text": (f"{label} is the date the page was sent ({m['from']})" if m.get("today")
                                         else f"{label} comes from the page record ({m['from']})")})
        elif kind == "const":
            form_fields[label] = {"const": m["value"]}
            if m.get("confirmed") is False:  # proposed, not typed by a person: the review asks
                assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "unconfirmed",
                                    "text": f"{label} is always {m['value']!r} (proposed; a person confirms it in the review)"})
            else:
                assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "inferred",
                                    "text": f"{label} is always {m['value']!r} (typed during the recording)"})
        else:
            f = _extractor_from_mapping(m)
            if f is None:
                problems.append(f"{label}: no selector or alternative to read it from the page")
                continue
            if f.get("jsonld") is not None and not f.get("jsonld_type"):  # V15: readers carry their @type
                f = learn.with_jsonld_types({"fields": {"f": f}}, html)["fields"]["f"]
            fname = m.get("field") or _field_name(label)
            fields[fname] = f
            form_fields[label] = {"from": fname}
            if m.get("transform"):
                form_fields[label]["transform"] = m["transform"]
