class ToolContext:
    """Per-thread state shared by the tools.

    Seams (methods, so tests can replace them): `validate_spec_text`, `compile_and_test`,
    `fetch_contract` (W1's engine) and `get_page_record` (W4a's page inbox)."""

    def __init__(self, svc: ThreadedAgentService, t: _Thread, name: str = NAME,
                 recording_id: str | None = None, incident_id: int | None = None, page_id: str | None = None):
        self.svc, self.t, self.name = svc, t, name
        self.recording_id, self.incident_id, self.page_id = recording_id, incident_id, page_id
        # LEARN state: values seen by passing candidates per field, ambiguity found in this thread,
        # answers to ambiguity questions, and the outcome for done.result
        self.passing_values: dict[str, dict[str, Any]] = {}
        self.ambiguous: dict[str, list[str]] = {}
        self.ambiguity_answers: dict[str, str] = {}
        self.learn_result: dict | None = None
        self.samples: list[dict] = []
        self.compile_attempts = 0
        self.failed_attempts = 0
        self.stopped = False
        self.deploy_requested = False
        self.deploy_result: dict | None = None
        self.last_version: dict | None = None
        self._interrupt_lock = threading.Lock()

    @property
    def mode(self) -> str:
        return self.t.mode

    @property
    def wd(self) -> Path:
        return work_dir(self.name)

    @property
    def spec_path(self) -> Path:
        return self.wd / "spec.yaml"

    def interrupt(self, type: str, **payload: Any) -> dict:
        with self._interrupt_lock:  # LangGraph may run tool calls in parallel; one pending interrupt at a time
            return self.svc.interrupt(self.t, type, **payload)

    # ---- helpers -------------------------------------------------------------------------
    def spec_dict(self) -> dict:
        return _yload(self.spec_path.read_text())

    def source_base(self) -> str:
        env = os.environ.get("PATCHWORK_SOURCE_BASE_URL")
        if env:
            return env.rstrip("/")
        if self.spec_path.exists():
            return self.spec_dict()["source"]["base_url"].rstrip("/")
        return candidates_for(self.recording_id or "fixture")["source"]["base_url"].rstrip("/")

    def sink_base(self) -> str:
        env = os.environ.get("PATCHWORK_SINK_BASE_URL")
        if env:
            return env.rstrip("/")
        if self.spec_path.exists():
            return self.spec_dict()["sink"]["base_url"].rstrip("/")
        return candidates_for(self.recording_id or "fixture")["sink"]["base_url"].rstrip("/")

    def auth_headers(self, part: str) -> dict[str, str]:
        """V13: headers for the control plane's own requests to the spec's `source` or `sink` ({} when the
        spec has no `auth` there, or there is no spec yet). Never shown to the model."""
        if not self.spec_path.exists():
            return {}
        try:
            return credentials.headers((self.spec_dict().get(part) or {}).get("auth"))
        except (AttributeError, TypeError, ValueError):
            return {}

    def credential_names(self) -> list[str]:
        """Every credential the workspace and this thread's draft spec reference (for redaction)."""
        spec = None
        if self.spec_path.exists():
            try:
                spec = self.spec_dict()
            except Exception:  # noqa: BLE001 - a half-written spec still gets the workspace's names
                spec = None
        return control_credentials.known_names(spec)

    def active_spec_text(self) -> str | None:
        active = Store().active_version(self.name)
        if not active:
            return None
        return (workspace_dir() / "integrations" / self.name / f"v{active}" / "spec.yaml").read_text()

    # ---- seams -----------------------------------------------------------------------------
    def validate_spec_text(self, text: str) -> list[str]:
        """Schema errors + lint (empty = valid)."""
        errors = validate_spec(text)
        if errors:
            return errors
        return lint_spec(_yload(text))

    def compile_and_test(self, spec_path: Path) -> dict:
        return ops.compile_and_test(spec_path)

    def fetch_contract(self, spec: dict) -> dict:
        """The destination's live contract document (OpenAPI, or the V6 form contract)."""
        fetch = getattr(ops, "fetch_contract", None)
        if fetch is not None:
            try:
                return fetch(parse_spec(spec))
            except (SpecError, TypeError, AttributeError):
                return fetch(spec)
        sink = spec.get("sink") or {}
        if sink.get("kind") == "form":
            from runner.forms import fetch_form_contract  # type: ignore[import-not-found]  # W1
            return fetch_form_contract(sink["url"])
        if sink.get("kind") == "airtable":
            return self.fetch_airtable_contract(sink["base_id"], sink["table"], (sink.get("auth") or {})["credential"])
        return ops.fetch_sink_openapi(sink["base_url"])

    def fetch_airtable_contract(self, base_id: str, table: str, credential: str) -> dict:
        """An Airtable table's V14 contract, read with the named credential (control-plane env)."""
        return ops.fetch_airtable_contract(base_id, table, credential)

    def get_page_record(self, page_id: str) -> dict:
        """A V1 page record from the control plane's page inbox."""
        try:
            from control.pages import PageInbox  # type: ignore[import-not-found]  # W4a
        except ImportError as e:
            raise KeyError(f"page inbox not available ({e})") from None
        rec = PageInbox().get(page_id)
        if rec is None:
            raise KeyError(f"page {page_id} not found")
        return rec

    def platform_pages(self, platform: str, exclude: str | None = None, limit: int = 5) -> list[dict]:
        """The newest stored pages from other tenants' hosts of `platform` (`*.myworkdayjobs.com`), at most `limit`."""
        try:
            from control.pages import PageInbox  # type: ignore[import-not-found]  # W4a
            pages = PageInbox().list(limit=1000)
        except Exception:  # noqa: BLE001
            return []
        out = [p for p in reversed(pages) if p.get("id") != exclude and match_rank({"site": platform}, p) == 1]
        return out[:limit]

    def learn_policy(self) -> str:
        return learn_policy()


