def check_candidate(parser: dict, rec: dict, spec: dict) -> dict:
    """Run a candidate parser and every LEARN check on one page or document. Pure: no events, no I/O. Shared by
    `test_page_parser`, `save_parser`, `add_site_parser` and the scripted agent (plan G5).

    Returns `{"error", "fields"}` when the candidate does not read the record, else `{fields, rows, skipped,
    evidence, rows_checks, ambiguous, evidence_ok, rows_ok, all_corroborated, cross_checks_passed}`. For a page
    `rows` and `rows_checks` are empty and `rows_ok` is true: the result is what the page checks always gave."""
    html_field, text_field = source_fields(spec)
    validate = spec.get("validate") or []
    doc = learn.is_document(rec) or bool((parser or {}).get("rows"))
    if doc:
        out = learn.run_document_parser(parser, rec, html_field, text_field)
        if "error" in out:
            return {"error": out["error"], "fields": out.get("fields", {})}
        fields, rows, skipped = out["fields"], out["rows"], out["skipped"]
    else:
        out = learn.run_page_parser(parser, rec, html_field, text_field)
        if "error" in out:
            return {"error": out["error"], "fields": out.get("fields", {})}
        fields, rows, skipped = out, [], []
    ev = learn.evidence(rec, fields, validate, parser=parser, html_field=html_field, text_field=text_field)
    for item in ev:  # a value written into the regex is not read from the page (`About Us (Visa)`)
        fixed = learn.literal_capture(str(((parser.get("fields") or {}).get(item["name"]) or {}).get("regex") or ""))
        if fixed is not None:
            item["ok"] = False
            item["detail"] = (f"the regex captures the fixed text {fixed!r}: it would write {fixed!r} for every "
                              "page. Read the value from the page instead (a JSON-LD field, a heading, a meta tag)")
    for item in ev:
        item["corroborated"] = learn.corroborated(rec, item["value"], html_field)
    amb = learn.ambiguity(rec, parser, html_field)
    checks = (learn.rows_checks(rec, parser, rows, validate, skipped=skipped, doc_fields=fields,
                                html_field=html_field, text_field=text_field) if parser.get("rows") else [])
    return {"fields": fields, "rows": rows, "skipped": skipped, "evidence": ev, "rows_checks": checks,
            "ambiguous": amb, "evidence_ok": all(i["ok"] for i in ev), "rows_ok": all(c["ok"] for c in checks),
            "all_corroborated": all(i["corroborated"] for i in ev),
            "cross_checks_passed": sum(1 for c in checks if c.get("cross") and c["ok"])}


class ToolContext:
    """Per-thread state shared by the tools.

    Seams (methods, so tests can replace them): `validate_spec_text`, `compile_and_test`,
    `fetch_contract` (W1's engine) and `get_page_record` (W4a's page inbox)."""

    def __init__(self, svc: ThreadedAgentService, t: _Thread, name: str = NAME,
                 recording_id: str | None = None, incident_id: int | None = None, page_id: str | None = None):
        self.svc, self.t, self.name = svc, t, name
        self.recording_id, self.incident_id, self.page_id = recording_id, incident_id, page_id
        # LEARN state: values seen by passing candidates per field, ambiguity found in this thread,
        # answers to ambiguity questions, and the outcome for done.result
        self.passing_values: dict[str, dict[str, Any]] = {}
        self.ambiguous: dict[str, list[str]] = {}
        self.ambiguity_answers: dict[str, str] = {}
        self.learn_result: dict | None = None
        self.samples: list[dict] = []
        self.compile_attempts = 0
        self.failed_attempts = 0
        self.stopped = False
        self.deploy_requested = False
        self.deploy_result: dict | None = None
        self.last_version: dict | None = None
        self._interrupt_lock = threading.Lock()
        # TEACH from examples: the review shown with request_deploy, and what a person decided per destination
        # field: {field: source_key of the source they chose}. A row counts as the person's only while its source
        # is still exactly that one (`person_chose`); every other value is labelled as proposed by AI.
        self.review: list[dict] | None = None
        self.confirmed: dict[str, str] = {}
        self.answers: dict[str, str] = {}  # destination field -> the person's ask_user answer about that field
        self._examples_c: dict | None = None
        self._contract: dict | None = None

    @property
    def mode(self) -> str:
        return self.t.mode

    @property
    def wd(self) -> Path:
        return work_dir(self.name)

    @property
    def spec_path(self) -> Path:
        return self.wd / "spec.yaml"

    def interrupt(self, type: str, **payload: Any) -> dict:
        with self._interrupt_lock:  # LangGraph may run tool calls in parallel; one pending interrupt at a time
            return self.svc.interrupt(self.t, type, **payload)

    # ---- helpers -------------------------------------------------------------------------
    def spec_dict(self) -> dict:
        return _yload(self.spec_path.read_text())

    def source_base(self) -> str:
        env = os.environ.get("PATCHWORK_SOURCE_BASE_URL")
        if env:
            return env.rstrip("/")
        if self.spec_path.exists():
            return self.spec_dict()["source"]["base_url"].rstrip("/")
        return candidates_for(self.recording_id or "fixture")["source"]["base_url"].rstrip("/")

    def sink_base(self) -> str:
        env = os.environ.get("PATCHWORK_SINK_BASE_URL")
        if env:
            return env.rstrip("/")
        if self.spec_path.exists():
            return self.spec_dict()["sink"]["base_url"].rstrip("/")
        return candidates_for(self.recording_id or "fixture")["sink"]["base_url"].rstrip("/")

    def auth_headers(self, part: str) -> dict[str, str]:
        """V13: headers for the control plane's own requests to the spec's `source` or `sink` ({} when the
        spec has no `auth` there, or there is no spec yet). Never shown to the model."""
        if not self.spec_path.exists():
            return {}
        try:
            return credentials.headers((self.spec_dict().get(part) or {}).get("auth"))
        except (AttributeError, TypeError, ValueError):
            return {}

    def credential_names(self) -> list[str]:
        """Every credential the workspace and this thread's draft spec reference (for redaction)."""
        spec = None
        if self.spec_path.exists():
            try:
                spec = self.spec_dict()
            except Exception:  # noqa: BLE001 - a half-written spec still gets the workspace's names
                spec = None
        return control_credentials.known_names(spec)

    def active_spec_text(self) -> str | None:
        active = Store().active_version(self.name)
        if not active:
            return None
        return (workspace_dir() / "integrations" / self.name / f"v{active}" / "spec.yaml").read_text()

    # ---- seams -----------------------------------------------------------------------------
    def validate_spec_text(self, text: str) -> list[str]:
        """Schema errors + lint (empty = valid)."""
        errors = validate_spec(text)
        if errors:
            return errors
        return lint_spec(_yload(text))

    def compile_and_test(self, spec_path: Path) -> dict:
        return ops.compile_and_test(spec_path)

    def fetch_contract(self, spec: dict) -> dict:
        """The destination's live contract document (OpenAPI, or the V6 form contract)."""
        fetch = getattr(ops, "fetch_contract", None)
        if fetch is not None:
            try:
                return fetch(parse_spec(spec))
            except (SpecError, TypeError, AttributeError):
                return fetch(spec)
        sink = spec.get("sink") or {}
        if sink.get("kind") == "form":
            from runner.forms import fetch_form_contract  # type: ignore[import-not-found]  # W1
            return fetch_form_contract(sink["url"])
        if sink.get("kind") == "airtable":
            return self.fetch_airtable_contract(sink["base_id"], sink["table"], (sink.get("auth") or {})["credential"])
        if sink.get("kind") == "sqlite":
            return ops.fetch_sqlite_contract(sink["path"], sink["table"])
        return ops.fetch_sink_openapi(sink["base_url"])

    def fetch_airtable_contract(self, base_id: str, table: str, credential: str) -> dict:
        """An Airtable table's V14 contract, read with the named credential (control-plane env)."""
        return ops.fetch_airtable_contract(base_id, table, credential)

    def get_page_record(self, page_id: str) -> dict:
        """A V1 page record (`pg-…`) or a V17 document record (`doc-…`) from the control plane's inbox."""
        try:
            from control.inboxes import inbox_for  # type: ignore[import-not-found]
        except ImportError as e:
            raise KeyError(f"page inbox not available ({e})") from None
        rec = inbox_for(page_id).get(page_id)
        if rec is None:
            raise KeyError(f"{'document' if str(page_id).startswith('doc-') else 'page'} {page_id} not found")
        return rec

    def platform_pages(self, platform: str, exclude: str | None = None, limit: int = 5) -> list[dict]:
        """The newest stored pages from other tenants' hosts of `platform` (`*.myworkdayjobs.com`), at most `limit`."""
        try:
            from control.autorun import page_filter  # type: ignore[import-not-found]  # W4a
            from control.pages import PageInbox  # type: ignore[import-not-found]  # W4a
            pages = PageInbox().list(limit=1000, **page_filter(self.name))  # V15: this integration's pages only
        except Exception:  # noqa: BLE001
            return []
        out = [p for p in reversed(pages) if p.get("id") != exclude and match_rank({"site": platform}, p) == 1]
        return out[:limit]

    def learn_policy(self) -> str:
        return learn_policy()

    # ---- TEACH from example pages ----------------------------------------------------------------
    def examples_candidates(self) -> dict | None:
        """The thread's candidates when they ask for TEACH from examples (`teach_mode: "examples"`), else None.
        Read from the workspace only (never the matcher), so other modes pay nothing for the check."""
        if self._examples_c is None and self.recording_id and self.t.mode == "build":
            path = workspace_dir() / "recordings" / self.recording_id / "candidates.json"
            try:
                c = json.loads(path.read_text()) if path.exists() else {}
            except (OSError, ValueError):
                c = {}
            self._examples_c = c if is_examples_candidates(c) else {}
        return self._examples_c or None

    def examples_mode(self) -> bool:
        return self.examples_candidates() is not None

    def example_records(self) -> list[dict]:
        """The example pages, in the order the person sent them: the inbox's records (V1), or records rebuilt
        from the draft's snapshots when the inbox no longer has a page."""
        c = self.examples_candidates() or {}
        out = []
        for i, ex in enumerate(c.get("examples") or []):
            try:
                out.append(self.get_page_record(str(ex.get("page_id"))))
            except KeyError:
                html = snapshot_html(self.recording_id or "", ex["snapshot"])
                rec = learn.make_page_record(ex.get("url") or "", html, seq=i + 1)
                if ex.get("page_id"):
                    rec["id"] = str(ex["page_id"])
                out.append(rec)
        return out

    def dest_contract(self) -> dict:
        """The destination's live contract (read once per thread)."""
        if self._contract is None:
            c = self.examples_candidates() or {}
            self._contract = self.fetch_contract({"sink": destination_sink(c.get("sink") or {}, {})})
        return self._contract


