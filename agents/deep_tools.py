def candidates_for(recording_id: str) -> dict:
    """workspace candidates.json -> matcher.match (if the capture workstream's matcher is present) ->
    the hand-made fixture (only for the fixture recording)."""
    path = workspace_dir() / "recordings" / recording_id / "candidates.json"
    if path.exists():
        return json.loads(path.read_text())
    try:
        from matcher import match  # type: ignore[import-not-found]
    except ImportError:
        match = None
    if match is not None:
        try:
            return match(load_recording(recording_id))
        except Exception:  # noqa: BLE001 - fall through to the fixture for the fixture recording
            if recording_id != "fixture":
                raise
    if recording_id == "fixture":
        return json.loads((FIXTURES / "agent_candidates.json").read_text())
    raise FileNotFoundError(f"no candidates for recording {recording_id} (no candidates.json and no matcher)")


def summarize_recording(rec: dict) -> str:
    lines = [f"intent: {rec.get('intent')}", f"allowlist: {rec.get('allowlist')}", f"events: {len(rec['events'])}"]
    for e in rec["events"]:
        typ = e.get("type")
        if typ == "framenavigated":
            lines.append(f"- navigate {e.get('url')} ({e.get('title')})")
        elif typ == "net":
            body = e.get("req") if e.get("method") in ("POST", "PUT", "PATCH") else None
            resp = e.get("resp")
            n = f"{len(resp)} items" if isinstance(resp, list) else "1 object"
            lines.append(f"- {e.get('method')} {e.get('url')} -> {e.get('status')}"
                         + (f" body={json.dumps(body)}" if body is not None else f" ({n})"))
        else:
            el = e.get("el") or {}
            label = el.get("label") or el.get("name") or el.get("testid") or el.get("css")
            val = e.get("value", e.get("text"))
            lines.append(f"- {typ} on {label!r}" + (f" value={val!r}" if val is not None else "")
                         + (f" (near {el.get('nearby')!r})" if el.get("nearby") else ""))
    return "\n".join(lines)


def summarize_openapi(doc: dict) -> str:
    out = []
    for path, ops_ in sorted(doc.get("paths", {}).items()):
        for method, op in ops_.items():
            line = f"{method.upper()} {path}"
            params = [p["name"] for p in op.get("parameters", []) if p.get("in") == "query"]
            if params:
                line += f" query={params}"
            schema = request_schema(doc, method, path)
            if schema:
                line += " body=" + json.dumps(_flatten_schema(doc, schema))
            out.append(line)
    return "\n".join(out)


def _resolve(doc: dict, schema: dict) -> dict:
    while isinstance(schema, dict) and "$ref" in schema:
        node: Any = doc
        for part in schema["$ref"][2:].split("/"):
            node = node.get(part, {})
        schema = node
    return schema or {}


def _flatten_schema(doc: dict, schema: dict) -> dict:
    schema = _resolve(doc, schema)
    props = {}
    for k, v in schema.get("properties", {}).items():
        v = _resolve(doc, v)
        desc = v.get("type", "any")
        if "enum" in v:
            desc += f" enum={v['enum']}"
        if "exclusiveMinimum" in v:
            desc += f" >{v['exclusiveMinimum']:g}"
        props[k] = desc
    return {"properties": props, "required": schema.get("required", []),
            **({"additionalProperties": False} if schema.get("additionalProperties") is False else {})}


def diff_request_schemas(old_doc: dict, new_doc: dict, method: str, path: str,
                         body_map: dict[str, dict] | None = None) -> dict:
    """Compare the request body schema of one operation and pair removed/added properties into
    likely renames: by name similarity first, then by matching the extracted field that fed the old
    property, then by unique type (enum-ness must agree)."""
    old = _flatten_schema(old_doc, request_schema(old_doc, method, path) or {})
    new = _flatten_schema(new_doc, request_schema(new_doc, method, path) or {})
    removed = {k: v for k, v in old["properties"].items() if k not in new["properties"]}
    added = {k: v for k, v in new["properties"].items() if k not in old["properties"]}
    body_map = body_map or {}
    renames: dict[str, str] = {}

    def base_type(d: str) -> tuple[str, bool]:
        return d.split()[0], "enum=" in d

    for r in list(removed):
        best = max(added, key=lambda a: difflib.SequenceMatcher(None, r, a).ratio(), default=None)
        if best and best not in renames.values() and (
                difflib.SequenceMatcher(None, r, best).ratio() >= 0.6 or best.startswith(r) or r.startswith(best)) \
                and base_type(removed[r]) == base_type(added[best]):
            renames[r] = best
    for r in removed:
        if r in renames:
            continue
        src = (body_map.get(r) or {}).get("from")
        if src and src in added and src not in renames.values():
            renames[r] = src
    for r in removed:
        if r in renames:
            continue
        same = [a for a in added if a not in renames.values() and base_type(added[a]) == base_type(removed[r])]
        if len(same) == 1:
            renames[r] = same[0]
    new_required = {a: added[a] for a in added if a not in renames.values() and a in new["required"]}
    return {"operation": f"{method} {path}", "removed": removed, "added": added,
            "likely_renames": renames, "new_required_unmapped": new_required,
            "old_required": old["required"], "new_required": new["required"]}


# ---- parsing against real samples ------------------------------------------------------------

def run_parser(parser: dict, text_field: str, record: dict) -> dict:
    fields = {}
    text = record.get(text_field) or ""
    for fname, f in parser["fields"].items():
        where = f"{parser.get('id', 'parser')}.{fname}"
        if f.get("regex") is not None:
            raw = extract_regex(text, re.compile(f["regex"]), where)
        elif f.get("between") is not None:
            raw = extract_between(text, f["between"][0], f["between"][1], where)
        elif f.get("json_path") is not None:
            raw = extract_json_path(record, f["json_path"], where)
        else:
            raise Quarantine("PARSE_NO_MATCH", f"{where}: no extract method")
        fields[fname] = cast(raw, f.get("cast", "str"), where)
    return fields


def _matches(match: dict, record: dict) -> bool:
    return all(str(record.get(k)) == str(v) for k, v in (match or {}).items())


def eval_value(vs: dict, fields: dict, record: dict) -> Any:
    """Evaluate a spec value source the way generated code does (used to migrate golden bodies)."""
    def ref(r: str) -> Any:
        return record[r.removeprefix("record.")] if r.startswith("record.") else fields[r]
    if "template" in vs:
        return re.sub(r"\{([A-Za-z_][A-Za-z0-9_.]*)\}", lambda m: str(ref(m.group(1))), vs["template"])
    if vs.get("transform"):
        name = vs["transform"]
        if name.startswith("custom:"):
            raise ValueError("custom transforms cannot be evaluated here")
        return getattr(T, name)(ref(vs["from"]), **(vs.get("args") or {}))
    if "from" in vs:
        return ref(vs["from"])
    return vs.get("const")


def lint_spec(spec: dict) -> list[str]:
    """Checks the schema can't express: lookup tables must cover every routed value, and the staging
    sink must never be the live sink."""
    problems = []
    sink = spec.get("sink", {})
    if sink.get("staging_base_url") and sink.get("staging_base_url", "").rstrip("/") == sink.get("base_url", "").rstrip("/"):
        problems.append("sink.staging_base_url must not equal sink.base_url (agents never write to live)")
    route_by = spec.get("extract", {}).get("route_by")
    routed = {str(p.get("match", {}).get(route_by)) for p in spec.get("extract", {}).get("parsers", [])
              if p.get("match", {}).get(route_by) is not None}
    for key, vs in sink.get("body", {}).items():
        if vs.get("transform") == "lookup" and vs.get("from") == f"record.{route_by}":
            table = (vs.get("args") or {}).get("table") or {}
            missing = sorted(routed - set(map(str, table)))
            if missing and (vs.get("args") or {}).get("default") is None:
                problems.append(f"sink.body.{key}: lookup table keys {sorted(table)} do not cover routed "
                                f"{route_by} values {missing}; use the exact values, e.g. {sorted(routed)}")
    return problems


def _short(obj: Any, n: int = 900) -> str:
    s = obj if isinstance(obj, str) else json.dumps(obj, default=str)
    return s if len(s) <= n else s[:n] + f"… (+{len(s) - n} chars)"


def _port_plus_one(url: str) -> str:
    p = urlparse(url)
    if p.port:
        return urlunparse(p._replace(netloc=f"{p.hostname}:{p.port + 1}"))
    return url


# ---- the tools ---------------------------------------------------------------------------

def build_tools(ctx: ToolContext) -> dict[str, StructuredTool]:
    """Return every tool by name; agents.deep hands each agent its subset."""

    def get_recording_summary(recording_id: str = "") -> str:
        """Summarize the user's recorded demonstration: navigations, user actions and API calls."""
        return summarize_recording(load_recording(recording_id or ctx.recording_id or "fixture"))

    def get_candidates(recording_id: str = "") -> str:
        """Matcher output: sink call, source record, and candidate mappings (dest field <- source label/regex)."""
        c = candidates_for(recording_id or ctx.recording_id or "fixture")
        rec = c.get("source", {}).get("record", {})
        slim = {**c, "source": {**c.get("source", {}), "record": {k: rec[k] for k in rec}}}
        return _short(slim, 3000)

    def read_openapi(target: str = "sink") -> str:
        """Summarize the destination ('sink') OpenAPI: operations, query params and request body schemas."""
        base = ctx.sink_base() if target == "sink" else ctx.source_base()
        doc = httpx.get(base + "/openapi.json", timeout=10).json()
        return summarize_openapi(doc)

    def fetch_source_samples(limit: int = 15) -> str:
        """Fetch `limit` real records (10-20 recommended) from the source API to test parsers against."""
        limit = max(1, min(int(limit), 40))
        c_list = "/api/messages"
        if ctx.spec_path.exists():
            c_list = ctx.spec_dict()["source"]["list"]["path"]
        recs = httpx.get(ctx.source_base() + c_list, params={"limit": limit}, timeout=10).json()[:limit]
        ctx.samples = recs
        groups: dict[str, int] = {}
        for r in recs:
            groups[str(r.get("sender_domain"))] = groups.get(str(r.get("sender_domain")), 0) + 1
        lines = [f"{len(recs)} records; by sender_domain: {groups}"]
        seen: dict[str, int] = {}
        for r in recs:  # show two bodies per group so the model sees every format
            g = str(r.get("sender_domain"))
            if seen.get(g, 0) < 2:
                seen[g] = seen.get(g, 0) + 1
                lines.append(f"- {r.get('id')} [{g}] {json.dumps((r.get('body') or '')[:220])}")
        return "\n".join(lines)

    def _ensure_samples() -> list[dict]:
        if not ctx.samples:
            fetch_source_samples(15)
        return ctx.samples

    def test_parser(parser: dict | None = None, parser_id: str = "") -> str:
        """Run extraction against the fetched real samples. With no arguments, test the whole current
        spec.yaml (routing + every parser). With `parser_id`, test that parser from spec.yaml. With
        `parser` ({id, match: {sender_domain: ...}, fields: {name: {regex, cast}}}), test a candidate
        parser before adding it."""
        samples = _ensure_samples()
        spec = ctx.spec_dict() if ctx.spec_path.exists() else {}
        text_field = spec.get("source", {}).get("text_field", "body")
        route_by = spec.get("extract", {}).get("route_by", "sender_domain")
        if parser is not None:
            parsers = [parser]
        elif parser_id:
            parsers = [p for p in spec.get("extract", {}).get("parsers", []) if p["id"] == parser_id]
            if not parsers:
                return f"ERROR: no parser {parser_id!r} in spec.yaml"
        else:
            parsers = spec.get("extract", {}).get("parsers", [])
        try:
            for p in parsers:
                for f in p["fields"].values():
                    if f.get("regex"):
                        re.compile(f["regex"])
        except (re.error, KeyError, AttributeError) as e:
            return f"ERROR: bad parser: {e}"
        lines, ok_total, n_total, uncovered = [], 0, 0, {}
        for p in parsers:
            subset = [r for r in samples if _matches(p.get("match", {}), r)]
            ok, fails, example = 0, [], None
            for r in subset:
                try:
                    fields = run_parser(p, text_field, r)
                    ok += 1
                    example = example or (r.get("id"), fields)
                except Quarantine as q:
                    fails.append(f"{r.get('id')}: {q.detail} | text={json.dumps((r.get(text_field) or '')[:160])}")
            ok_total, n_total = ok_total + ok, n_total + len(subset)
            lines.append(f"{p.get('id', 'parser')} (match {p.get('match')}): {ok}/{len(subset)} extracted"
                         + (f"; e.g. {example[0]} -> {example[1]}" if example else ""))
            lines += [f"  FAIL {f}" for f in fails[:4]]
        if parser is None:
            for r in samples:
                if not any(_matches(p.get("match", {}), r) for p in parsers):
                    uncovered.setdefault(str(r.get(route_by)), []).append(r.get("id"))
            for route, ids in uncovered.items():
                body = next((x.get(text_field) for x in samples if x.get("id") == ids[0]), "")
                lines.append(f"NO PARSER for {route_by}={route}: {len(ids)} records, e.g. {ids[0]} "
                             f"text={json.dumps((body or '')[:200])}")
        verdict = "OK" if ok_total == n_total and not uncovered else "FAILED"
        return f"{verdict}: {ok_total}/{n_total} matched records extracted\n" + "\n".join(lines)

    def draft_spec(field_names: dict[str, str] | None = None) -> str:
        """Write a first spec.yaml + examples.yaml from the recording's candidates (deterministic code).
        `field_names` optionally renames extracted fields, e.g. {"product_id": "sku", "quantity": "qty",
        "reference": "po_id"} (destination field -> short extracted field name). Overwrites spec.yaml."""
        c = candidates_for(ctx.recording_id or "fixture")
        rec = load_recording(ctx.recording_id or "fixture")
        field_names = field_names or {}
        src, sink, record = c["source"], c["sink"], c["source"]["record"]
        route_by = "sender_domain" if "sender_domain" in record else None
        route_val = record.get(route_by) if route_by else None
        pid = (re.sub(r"[^a-z0-9]+", "_", str(route_val).split(".")[0].lower()) if route_val else "main") + "_v1"
        fields, body, assumptions = {}, {}, []
        for m in c["mappings"]:
            fname = re.sub(r"[^a-z0-9_]", "_", field_names.get(m["dest_field"], m["dest_field"]).lower())
            if m["kind"] == "json":
                fields[fname] = {"json_path": m["json_path"]}
            else:
                fields[fname] = {"regex": m["candidate_regex"]}
            if (m.get("cast") or "str") != "str":
                fields[fname]["cast"] = m["cast"]
            body[m["dest_field"]] = {"from": fname}
            assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "observed",
                                "text": f"{m['dest_field']} comes from the {m.get('label') or m.get('json_path')} value"})
        for u in c.get("unexplained", []):
            body[u["dest_field"]] = {"const": u["value"]}
            assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "inferred",
                                "text": f"{u['dest_field']} is always {u['value']!r} (not found in the source)"})
        validate = [{"field": f, "rule": "positive_int"} for f, d in fields.items() if d.get("cast") == "int"]
        sink_base = ctx.sink_base()
        try:
            doc = httpx.get(sink_base + "/openapi.json", timeout=10).json()
        except httpx.HTTPError:
            doc = {}
        # existence checks: a GET /x/{id} that answers 200 for the recorded value and 404 for a bogus one
        for path, ops_ in doc.get("paths", {}).items():
            params = re.findall(r"\{(\w+)\}", path)
            if "get" not in ops_ or len(params) != 1 or not path.endswith("}"):
                continue
            for m in c["mappings"]:
                fname = re.sub(r"[^a-z0-9_]", "_", field_names.get(m["dest_field"], m["dest_field"]).lower())
                if not isinstance(m["value"], str) or any(v.get("field") == fname for v in validate):
                    continue
                try:
                    good = httpx.get(sink_base + path.replace("{" + params[0] + "}", m["value"]), timeout=5)
                    bad = httpx.get(sink_base + path.replace("{" + params[0] + "}", "PATCHWORK-NOPE"), timeout=5)
                except httpx.HTTPError:
                    continue
                if good.status_code == 200 and bad.status_code == 404:
                    validate.append({"field": fname, "rule": "exists",
                                     "check": {"method": "GET", "path": path.replace("{" + params[0] + "}", "{" + fname + "}")}})
        verify = None
        get_op = doc.get("paths", {}).get(sink["path"], {}).get("get")
        if get_op:
            for p in get_op.get("parameters", []):
                if p.get("in") == "query" and p["name"] in body and "from" in body[p["name"]]:
                    verify = {"method": "GET", "path": sink["path"], "params": {p["name"]: "{" + body[p["name"]]["from"] + "}"},
                              "expect_count": 1}
                    break
        key = [body[k]["from"] for k in body if k in ("reference", "ref", "id", "order_id") and "from" in body[k]] \
            or [d["from"] for d in body.values() if "from" in d]
        assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "inferred",
                            "text": f"{', '.join(key)} identifies a record; resends are duplicates"})
        assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "inferred",
                            "text": "Messages the parsers can't read are quarantined for review, not dropped"})
        source = {"kind": "api", "base_url": src["base_url"],
                  "list": {"method": src["list"]["method"], "path": src["list"]["path"]},
                  "record_id": src["record_id"], "text_field": src["text_field"]}
        if "received_at" in record:
            source["list"]["params"] = {"since": "{cursor}"}
            source["cursor_field"] = "received_at"
        spec = {
            "spec_version": 1, "name": ctx.name, "intent": rec.get("intent") or c.get("intent", ""),
            "source": source,
            "extract": {"route_by": route_by or src["record_id"],
                        "parsers": [{"id": pid, "match": {route_by: route_val} if route_by else {}, "fields": fields}]},
            "validate": validate, "dedupe": {"key": key},
            "sink": {"kind": "api", "base_url": sink["base_url"], "staging_base_url": _port_plus_one(sink["base_url"]),
                     "call": {"method": sink["method"], "path": sink["path"]}, "body": body,
                     **({"verify": verify} if verify else {})},
            "on_error": "quarantine", "assumptions": assumptions,
        }
        errors = validate_spec(yaml.safe_dump(spec))
        ctx.spec_path.write_text(yaml.safe_dump(spec, sort_keys=False, width=200))
        examples = [{"name": f"recorded_{re.sub(r'[^a-z0-9]+', '_', str(record.get(src['record_id'])).lower())}",
                     "record": record, "expect": {"body": sink["body"]}}]
        (ctx.wd / "examples.yaml").write_text(yaml.safe_dump(examples, sort_keys=False, width=200))
        ctx.svc.emit(ctx.t, "artifact", kind="spec", name=ctx.name, version=None, path=str(ctx.spec_path))
        return (f"wrote spec.yaml (parser {pid}, {len(fields)} fields, {len(validate)} rules, dedupe {key}"
                f"{', verify' if verify else ''}) and examples.yaml (1 recorded example). "
                + ("valid" if not errors else "INVALID: " + "; ".join(errors)))

    def validate_spec_tool() -> str:
        """Validate the current spec.yaml (closed vocabulary). Returns 'valid' or the errors to fix."""
        if not ctx.spec_path.exists():
            return "ERROR: no spec.yaml yet"
        errors = validate_spec(ctx.spec_path.read_text()) + lint_spec(ctx.spec_dict())
        return "valid" if not errors else "INVALID:\n" + "\n".join(f"- {e}" for e in errors)

    def propose_spec_patch(patch: list[dict], reason: str = "") -> str:
        """Apply an RFC 6902 JSON Patch to spec.yaml (the spec only; runtime code is regenerated by the
        compiler). Paths look like /sink/body/sku or /extract/parsers/- . The patch is applied only if the
        resulting spec is valid; otherwise nothing is written and the errors are returned."""
        if not ctx.spec_path.exists():
            return "REFUSED: no spec.yaml to patch"
        old = ctx.spec_dict()
        if any(str(op.get("path", "")).startswith(("/name", "/sink/base_url", "/source/base_url")) for op in patch):
            return "REFUSED: name and base URLs are fixed; patch the mapping, parsers, rules or assumptions"
        try:
            new = jsonpatch.apply_patch(old, patch)
        except (jsonpatch.JsonPatchException, jsonpatch.JsonPointerException, TypeError, KeyError) as e:
            return f"REFUSED: patch does not apply: {e}"
        errors = validate_spec(yaml.safe_dump(new)) + lint_spec(new)
        if errors:
            return "REFUSED (spec unchanged):\n" + "\n".join(f"- {e}" for e in errors)
        ctx.spec_path.write_text(yaml.safe_dump(new, sort_keys=False, width=200))
        ctx.svc.emit(ctx.t, "artifact", kind="spec", name=ctx.name, version=None, path=str(ctx.spec_path))
        return f"applied {len(patch)} operation(s); spec.yaml is valid"

    def add_test_case(record_id: str, expect_body: dict | None = None, expect_quarantine: str = "",
                      missing: list[str] | None = None) -> str:
        """Add a golden example to examples.yaml from a real source record: either the exact sink body it
        must produce (expect_body) or the quarantine code it must end in (PARSE_NO_MATCH,
        VALIDATION_FAILED, NOT_FOUND). `missing` lists ids the existence check should treat as unknown."""
        rec = next((r for r in ctx.samples if str(r.get("id")) == record_id), None)
        if rec is None:
            try:
                path = ctx.spec_dict()["source"]["list"]["path"] if ctx.spec_path.exists() else "/api/messages"
                resp = httpx.get(f"{ctx.source_base()}{path}/{record_id}", timeout=10)
                resp.raise_for_status()
                rec = resp.json()
            except httpx.HTTPError as e:
                return f"ERROR: record {record_id} not found: {e}"
        expect = {"body": expect_body} if expect_body is not None else {"quarantine": expect_quarantine}
        name = re.sub(r"[^a-z0-9]+", "_", f"{rec.get('sender_domain', 'rec').split('.')[0]}_{record_id}".lower())
        ex = {"name": name, "record": rec, "expect": expect, **({"missing": missing} if missing else {})}
        try:
            Example.parse(ex)
        except CompileError as e:
            return f"REFUSED: {e}"
        path = ctx.wd / "examples.yaml"
        examples = [e for e in (yaml.safe_load(path.read_text()) if path.exists() else []) or [] if e["name"] != name]
        examples.append(ex)
        path.write_text(yaml.safe_dump(examples, sort_keys=False, width=200))
        return f"added example {name} ({'body' if expect_body is not None else expect_quarantine}); {len(examples)} examples total"

    def compile_spec() -> str:
        """Compile spec.yaml (+ examples.yaml, transforms.py) into the next immutable version and run its
        full generated test suite. Refuses invalid specs. Never deploys."""
        if ctx.stopped:
            return "REFUSED: the user asked to stop this repair"
        if not ctx.spec_path.exists():
            return "REFUSED: no spec.yaml"
        errors = validate_spec(ctx.spec_path.read_text()) + lint_spec(ctx.spec_dict())
        if errors:
            return "REFUSED: spec is invalid, fix it first:\n" + "\n".join(f"- {e}" for e in errors)
        if ctx.mode == "repair" and ctx.failed_attempts >= MAX_REPAIR_ATTEMPTS:
            answer = ctx.interrupt(
                "ask_user", question=f"I couldn't get the tests green after {MAX_REPAIR_ATTEMPTS} repair attempts. "
                                     "How should I proceed?",
                options=["Stop the repair; I'll take it from here", "Try 3 more times"])
            if "more" not in str(answer.get("answer", "")).lower():
                ctx.stopped = True
                return "REFUSED: user stopped the repair after 3 failed attempts. Stop now and report."
            ctx.failed_attempts = 0
        ctx.compile_attempts += 1
        try:
            built = ops.compile_and_test(ctx.spec_path)
        except (CompileError, SpecError) as e:
            ctx.failed_attempts += 1
            return f"ERROR: compile failed: {e}"
        ctx.last_version = built
        ctx.svc.emit(ctx.t, "artifact", kind="package", name=ctx.name, version=built["version"], path=built["path"])
        if not built["tests_passed"]:
            ctx.failed_attempts += 1
            tail = "\n".join(built["tests_summary"].splitlines()[-25:])
            left = MAX_REPAIR_ATTEMPTS - ctx.failed_attempts if ctx.mode == "repair" else None
            return (f"FAILED: v{built['version']} compiled but tests failed"
                    + (f" ({left} repair attempts left)" if left is not None else "") + f":\n{tail}")
        extra = f"; contract warnings: {built['contract_errors']}" if built["contract_errors"] else ""
        return f"compiled v{built['version']}: tests passed ({built['tests_summary']}){extra}"

    def run_tests(version: int) -> str:
        """Re-run the full generated test suite of a compiled version."""
        passed, summary = ops.run_tests(ctx.name, int(version))
        return (f"v{version}: passed ({summary})" if passed
                else f"FAILED: v{version}:\n" + "\n".join(summary.splitlines()[-25:]))

    def dry_run(limit: int = 10) -> str:
        """Run the latest passing version against the STAGING sink only, on `limit` real records."""
        store = Store()
        passing = [v for v in store.versions(ctx.name) if v["tests_passed"]]
        if not passing:
            return "REFUSED: no compiled version has passing tests yet"
        v = passing[-1]["version"]
        vdir = workspace_dir() / "integrations" / ctx.name / f"v{v}"
        cfg = yaml.safe_load((vdir / "config.yaml").read_text())
        staging = (os.environ.get("PATCHWORK_STAGING_BASE_URL") or cfg["sink"].get("staging_base_url") or "").rstrip("/")
        live = (os.environ.get("PATCHWORK_SINK_BASE_URL") or cfg["sink"]["base_url"]).rstrip("/")
        if not staging or staging == live:
            return "REFUSED: no separate staging sink configured; agents never write to the live sink"
        try:
            s = ops.run_sandboxed(ctx.name, version=str(v), dry_run=True, limit=max(1, min(int(limit), 25)), timeout=120)
        except Exception as e:  # noqa: BLE001
            return f"ERROR: dry run unavailable: {e}"
        ok = s.get("status") == "completed"
        return (("" if ok else "FAILED: ") + f"dry run of v{v} on staging: {s.get('status')} {s.get('counts')}"
                + (f" ({s.get('message')})" if s.get("message") else ""))

    def get_incident(incident_id: int = 0) -> str:
        """Read an incident: type, summary, contract errors, the active version."""
        inc = Store().incident(int(incident_id or ctx.incident_id or 0))
        if inc is None:
            return f"ERROR: incident {incident_id} not found"
        detail = inc.get("detail") or {}
        return _short({"id": inc["id"], "integration": inc["integration"], "version": inc["version"],
                       "type": inc["type"], "reason_codes": inc["reason_codes"], "summary": inc["summary"],
                       "contract_errors": sorted(set(e.split("] ", 1)[-1] for e in detail.get("contract_errors", []))),
                       "sink_call": detail.get("sink_call"), "samples": (inc.get("samples") or [])[:3],
                       "has_openapi_diff": bool(inc.get("old_openapi") and inc.get("new_openapi"))}, 2500)

    def get_quarantined(limit: int = 10) -> str:
        """Recent quarantined records of this integration (record id, reason, detail, text snippet)."""
        store, out = Store(), []
        for run in store.runs(ctx.name, limit=5):
            for r in store.records(run["id"]):
                if r["status"] == "quarantined":
                    out.append({"record_id": r["record_id"], "reason": r["reason"], "detail": (r["detail"] or "")[:160],
                                "route": r["route_value"], "text": (r["raw"].get("body") or "")[:160]})
                if len(out) >= int(limit):
                    break
        return _short(out, 3000) if out else "no quarantined records"

    def diff_openapi() -> str:
        """Diff the destination OpenAPI the active version was compiled against (old) with the live one
        (new) for the sink call, and pair removed/added properties into likely renames."""
        inc = Store().incident(int(ctx.incident_id or 0)) if ctx.incident_id else None
        spec = ctx.spec_dict()
        method, path = spec["sink"]["call"]["method"], spec["sink"]["call"]["path"]
        if inc and inc.get("old_openapi") and inc.get("new_openapi"):
            old_doc, new_doc = inc["old_openapi"], inc["new_openapi"]
        else:
            active = Store().active_version(ctx.name)
            old_doc = json.loads((workspace_dir() / "integrations" / ctx.name / f"v{active}" / "contract" / "openapi.json").read_text())
            new_doc = httpx.get(ctx.sink_base() + "/openapi.json", timeout=10).json()
        d = diff_request_schemas(old_doc, new_doc, method, path, spec["sink"]["body"])
        d["current_sink_body"] = spec["sink"]["body"]
        routed = sorted({str(p.get("match", {}).get(spec["extract"]["route_by"])) for p in spec["extract"]["parsers"]})
        d["routed_values"] = {spec["extract"]["route_by"]: routed}
        return json.dumps(d, indent=1)

    def migrate_golden_examples() -> str:
        """After patching sink.body for a new destination contract, rewrite every golden example's
        expected body to the new shape: values fed by the same extracted field are carried over from the
        old expected body; new fields (const, lookup on record.*) are computed from the patched spec."""
        path = ctx.wd / "examples.yaml"
        if not path.exists():
            return "ERROR: no examples.yaml"
        active = ctx.active_spec_text()
        if active is None:
            return "ERROR: no active version to migrate from"
        old_body = yaml.safe_load(active)["sink"]["body"]
        new_body = ctx.spec_dict()["sink"]["body"]
        by_field = {vs["from"]: k for k, vs in old_body.items() if "from" in vs and "transform" not in vs}
        examples = yaml.safe_load(path.read_text()) or []
        changed, problems = 0, []
        for ex in examples:
            body = ex.get("expect", {}).get("body")
            if body is None:
                continue
            out = {}
            for k, vs in new_body.items():
                if "from" in vs and "transform" not in vs and vs["from"] in by_field and by_field[vs["from"]] in body:
                    out[k] = body[by_field[vs["from"]]]
                else:
                    try:
                        out[k] = eval_value(vs, {}, ex["record"])
                    except (Quarantine, KeyError, ValueError, TypeError) as e:
                        problems.append(f"{ex['name']}.{k}: {e}")
            if out != body:
                ex["expect"]["body"] = out
                changed += 1
        if problems:
            return "REFUSED (examples unchanged): " + "; ".join(problems[:5])
        path.write_text(yaml.safe_dump(examples, sort_keys=False, width=200))
        sample = next((e["expect"]["body"] for e in examples if "body" in e.get("expect", {})), None)
        return f"rewrote {changed} expected bodies; e.g. {json.dumps(sample)}"

    def ask_user(question: str, options: list[str] | None = None) -> str:
        """Ask the human one short question (with 2-3 options) and wait for the answer. Use it to
        confirm inferred assumptions and for values that cannot be derived from the data."""
        answer = ctx.interrupt("ask_user", question=question, options=list(options or []))
        return f"user answered: {answer.get('answer', '')}"

    def request_deploy(version: int, summary: str) -> str:
        """Ask the human to approve deploying a compiled version. Refused unless that exact version passed
        its full test suite. On approval the version is deployed (and, in REPAIR, quarantined records are
        replayed)."""
        store = Store()
        v = store.version(ctx.name, int(version))
        if v is None:
            return f"REFUSED: {ctx.name} v{version} does not exist"
        if not v["tests_passed"]:
            return f"REFUSED: v{version} has not passed its full test suite; fix and recompile first"
        if ctx.deploy_requested and ctx.deploy_result and ctx.deploy_result.get("deployed"):
            return f"REFUSED: v{ctx.deploy_result['version']} was already deployed in this thread"
        ctx.deploy_requested = True
        vdir = workspace_dir() / "integrations" / ctx.name / f"v{version}"
        new_text = (vdir / "spec.yaml").read_text()
        prev = store.active_version(ctx.name)
        spec_diff, code_diff, patch = new_text, "", None
        if prev:
            prev_dir = workspace_dir() / "integrations" / ctx.name / f"v{prev}"
            old_text = (prev_dir / "spec.yaml").read_text()
            spec_diff = "".join(difflib.unified_diff(old_text.splitlines(True), new_text.splitlines(True),
                                                     f"spec.yaml (v{prev}, active)", f"spec.yaml (v{version})"))
            for f in ("integration.py", "parsers.py", "adapters.py", "transforms.py"):
                if (prev_dir / f).exists() and (vdir / f).exists():
                    code_diff += "".join(difflib.unified_diff(
                        (prev_dir / f).read_text().splitlines(True), (vdir / f).read_text().splitlines(True),
                        f"v{prev}/{f}", f"v{version}/{f}"))
            patch = jsonpatch.make_patch(yaml.safe_load(old_text), yaml.safe_load(new_text)).patch
        payload: dict[str, Any] = dict(name=ctx.name, version=int(version), summary=summary, spec_diff=spec_diff,
                                       code_diff=code_diff,
                                       tests={"passed": bool(v["tests_passed"]), "summary": v["tests_summary"]})
        if ctx.mode == "repair" and patch is not None:
            payload["spec_patch"] = patch
        answer = ctx.interrupt("request_deploy", **payload)
        if answer.get("decision") != "approve":
            ctx.deploy_result = {"deployed": False, "version": int(version), "comment": answer.get("comment", "")}
            return f"REJECTED by the user: {answer.get('comment', '')}. Do not deploy; report and stop."
        try:
            result = ops.deploy(ctx.name, int(version))
        except ops.DeployRefused as e:
            return f"REFUSED: {e}"
        ctx.svc.emit(ctx.t, "deployed", name=ctx.name, version=int(version), previous_version=result["previous_version"])
        ctx.deploy_result = {"deployed": True, "version": int(version)}
        msg = f"deployed v{version} (previous v{result['previous_version']})"
        replay = getattr(ops, "replay_quarantined", None)
        if ctx.mode == "repair" and replay is not None:
            try:
                r = replay(ctx.name)
                msg += f"; replayed quarantined records: {_short(r, 300)}"
            except Exception as e:  # noqa: BLE001 - replay is best effort; the deploy already happened
                msg += f"; replay failed: {e}"
        return msg + ". Done: report the result in one sentence."

    fns = {
        "get_recording_summary": get_recording_summary, "get_candidates": get_candidates,
        "read_openapi": read_openapi, "fetch_source_samples": fetch_source_samples, "test_parser": test_parser,
        "draft_spec": draft_spec, "validate_spec": validate_spec_tool, "propose_spec_patch": propose_spec_patch,
        "add_test_case": add_test_case, "compile_spec": compile_spec, "run_tests": run_tests, "dry_run": dry_run,
        "get_incident": get_incident, "get_quarantined": get_quarantined, "diff_openapi": diff_openapi,
        "migrate_golden_examples": migrate_golden_examples, "ask_user": ask_user, "request_deploy": request_deploy,
    }
    return {name: StructuredTool.from_function(fn, name=name) for name, fn in fns.items()}


def seed_repair_workdir(name: str) -> Path:
    """REPAIR starts from the active version (the source of truth), not from whatever is in work/."""
    store = Store()
    active = store.active_version(name)
    if not active:
        raise RuntimeError(f"{name} has no active version to repair")
    vdir = workspace_dir() / "integrations" / name / f"v{active}"
    wd = work_dir(name)
    (wd / "spec.yaml").write_text((vdir / "spec.yaml").read_text())
    golden = json.loads((vdir / "golden.json").read_text())
    examples = [{k: v for k, v in ex.items() if not (k == "missing" and not v)} for ex in golden]
    (wd / "examples.yaml").write_text(yaml.safe_dump(examples, sort_keys=False, width=200))
    spec = load_spec(wd / "spec.yaml")
    if spec.custom_transforms():
        (wd / "transforms.py").write_text((vdir / "transforms.py").read_text())
    return wd


