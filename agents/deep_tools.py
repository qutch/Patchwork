    def test_parser(parser: dict | None = None, parser_id: str = "") -> str:
        """Run extraction against the fetched real samples. With no arguments, test the whole current
        spec.yaml (routing + every parser). With `parser_id`, test that parser from spec.yaml. With
        `parser` ({id, match: {sender_domain: ...}, fields: {name: {regex, cast}}}), test a candidate
        parser before adding it."""
        samples = _ensure_samples()
        spec = ctx.spec_dict() if ctx.spec_path.exists() else {}
        text_field = spec.get("source", {}).get("text_field", "body")
        html_field = spec.get("source", {}).get("html_field")
        route_by = spec.get("extract", {}).get("route_by", "sender_domain")
        if parser is not None:
            parsers = [parser]
        elif parser_id:
            parsers = [p for p in spec.get("extract", {}).get("parsers", []) if p["id"] == parser_id]
            if not parsers:
                return f"ERROR: no parser {parser_id!r} in spec.yaml"
        else:
            parsers = spec.get("extract", {}).get("parsers", [])
        try:
            for p in parsers:
                for f in p["fields"].values():
                    if f.get("regex"):
                        re.compile(f["regex"])
        except (re.error, KeyError, AttributeError) as e:
            return f"ERROR: bad parser: {e}"
        lines, ok_total, n_total, uncovered = [], 0, 0, {}
        for p in parsers:
            subset = [r for r in samples if _matches(p.get("match", {}), r)]
            ok, fails, example = 0, [], None
            for r in subset:
                try:
                    fields = run_parser(p, text_field, r, html_field)
                    ok += 1
                    example = example or (r.get("id"), fields)
                except Quarantine as q:
                    fails.append(f"{r.get('id')}: {q.detail} | text={json.dumps((r.get(text_field) or '')[:160])}")
            ok_total, n_total = ok_total + ok, n_total + len(subset)
            lines.append(f"{p.get('id', 'parser')} (match {p.get('match')}): {ok}/{len(subset)} extracted"
                         + (f"; e.g. {example[0]} -> {example[1]}" if example else ""))
            lines += [f"  FAIL {f}" for f in fails[:4]]
        if parser is None:
            for r in samples:
                if not any(_matches(p.get("match", {}), r) for p in parsers):
                    uncovered.setdefault(str(r.get(route_by)), []).append(r.get("id"))
            for route, ids in uncovered.items():
                body = next((x.get(text_field) for x in samples if x.get("id") == ids[0]), "")
                lines.append(f"NO PARSER for {route_by}={route}: {len(ids)} records, e.g. {ids[0]} "
                             f"text={json.dumps((body or '')[:200])}")
        verdict = "OK" if ok_total == n_total and not uncovered else "FAILED"
        return f"{verdict}: {ok_total}/{n_total} matched records extracted\n" + "\n".join(lines)

    def _airtable_target(c: dict, dest: dict) -> dict:
        """V14 TEACH retarget: map each recorded form label to the Airtable field with the same normalised
        name; ask a person about every label without one (code asks, never guesses)."""
        from runner.airtable import properties
        try:
            contract = ctx.fetch_airtable_contract(dest["base_id"], dest["table"], dest["credential"])
        except Exception as e:  # noqa: BLE001 - said to the model; never shows a credential value
            from runner.credentials import redact
            raise ValueError(f"cannot read the Airtable table {dest['table']!r}: "
                             f"{redact(e, names=[dest['credential']])}") from None
        writable = list(properties(contract))
        by_norm = {norm_label(f): f for f in writable}
        labels = [lab for lab in (c["sink"].get("labels") or [m["dest_field"] for m in c.get("mappings") or []])
                  if any(m.get("dest_field") == lab for m in c.get("mappings") or [])]
        labels += [u["dest_field"] for u in c.get("unexplained") or [] if u["dest_field"] not in labels]
        names: dict[str, str | None] = {lab: by_norm.get(norm_label(lab)) for lab in labels}
        for lab in [lab for lab, n in names.items() if n is None]:
            free = [f for f in writable if f not in names.values()]
            options = free + [SKIP_FIELD]
            answer = str(ctx.interrupt(
                "ask_user", question=f"The form question {lab!r} has no field with that name in the Airtable table "
                                     f"{dest['table']!r}. Which field should get it?",
                options=options).get("answer", "")).strip()
            chosen = next((f for f in free if norm_label(f) == norm_label(answer)), None)
            if chosen:
                names[lab] = chosen
            elif norm_label(answer) in (norm_label(SKIP_FIELD), "skip", "none") or answer.lower().startswith(("skip", "none")):
                names[lab] = None
            else:
                raise ValueError(f"the answer {answer!r} for {lab!r} is not one of {options}; nothing written")
        return {"base_id": dest["base_id"], "table": dest["table"], "credential": dest["credential"],
                "fields": names, "contract": contract}

    def draft_spec(field_names: dict[str, str] | None = None) -> str:
        """Write a first spec.yaml + examples.yaml from the recording's candidates (deterministic code).
        `field_names` optionally renames extracted fields, e.g. {"product_id": "sku", "quantity": "qty",
        "reference": "po_id"} (destination field -> short extracted field name). Overwrites spec.yaml."""
        c = candidates_for(ctx.recording_id or "fixture")
        if is_page_candidates(c):
            try:
                html = snapshot_html(ctx.recording_id or JOBS_RECORDING, c["source"]["snapshot"])
            except (FileNotFoundError, KeyError) as e:
                return f"ERROR: {e}"
            airtable = None
            dest = destination_of(c)
            if dest:
                try:
                    airtable = _airtable_target(c, dest)
                except ValueError as e:
                    return f"ERROR: {e}"
            spec, examples, problems = draft_page_spec(c, name=ctx.name, thread_id=ctx.t.id, html=html,
                                                       airtable=airtable)
            ctx.spec_path.write_text(_ydump(spec, sort_keys=False, width=200))
            (ctx.wd / "examples.yaml").write_text(_ydump(examples, sort_keys=False, width=200))
            ctx.samples = [examples[0]["record"]]
            errors = ctx.validate_spec_text(ctx.spec_path.read_text())
            ctx.svc.emit(ctx.t, "artifact", kind="spec", name=ctx.name, version=None, path=str(ctx.spec_path))
            p = spec["extract"]["parsers"][0]
            readers = {k: learn.extractor_label(v) for k, v in p["fields"].items()}
            where = (f"page -> Airtable table {spec['sink']['table']!r}" if airtable else "page -> form")
            what = "Airtable fields" if airtable else "form fields"
            skipped = [lab for lab, n in (airtable or {}).get("fields", {}).items() if not n]
            return (f"wrote spec.yaml ({where}: parser {p['id']} for {p['match']['site']}, fields {readers}, "
                    f"{what} {list(spec['sink']['fields'])}"
                    + (f" (skipped: {skipped})" if skipped else "")
                    + ", dedupe record.canonical_url) and examples.yaml "
                    "(the recorded page). "
                    + ("; ".join(f"PROBLEM: {x}" for x in problems) + ". " if problems else "")
                    + ("valid" if not errors else "INVALID: " + "; ".join(errors)))
        rec = load_recording(ctx.recording_id or "fixture")
        field_names = field_names or {}
        src, sink, record = c["source"], c["sink"], c["source"]["record"]
        route_by = "sender_domain" if "sender_domain" in record else None
        route_val = record.get(route_by) if route_by else None
        pid = (re.sub(r"[^a-z0-9]+", "_", str(route_val).split(".")[0].lower()) if route_val else "main") + "_v1"
        fields, body, assumptions = {}, {}, []
        for m in c["mappings"]:
            fname = re.sub(r"[^a-z0-9_]", "_", field_names.get(m["dest_field"], m["dest_field"]).lower())
            if m["kind"] == "json":
                fields[fname] = {"json_path": m["json_path"]}
            else:
                fields[fname] = {"regex": m["candidate_regex"]}
            if (m.get("cast") or "str") != "str":
                fields[fname]["cast"] = m["cast"]
            body[m["dest_field"]] = {"from": fname}
            assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "observed",
                                "text": f"{m['dest_field']} comes from the {m.get('label') or m.get('json_path')} value"})
        for u in c.get("unexplained", []):
            body[u["dest_field"]] = {"const": u["value"]}
            assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "inferred",
                                "text": f"{u['dest_field']} is always {u['value']!r} (not found in the source)"})
        validate = [{"field": f, "rule": "positive_int"} for f, d in fields.items() if d.get("cast") == "int"]
        sink_base = ctx.sink_base()
        try:
            doc = httpx.get(sink_base + "/openapi.json", timeout=10).json()
        except httpx.HTTPError:
            doc = {}
        # existence checks: a GET /x/{id} that answers 200 for the recorded value and 404 for a bogus one
        for path, ops_ in doc.get("paths", {}).items():
            params = re.findall(r"\{(\w+)\}", path)
            if "get" not in ops_ or len(params) != 1 or not path.endswith("}"):
                continue
            for m in c["mappings"]:
                fname = re.sub(r"[^a-z0-9_]", "_", field_names.get(m["dest_field"], m["dest_field"]).lower())
                if not isinstance(m["value"], str) or any(v.get("field") == fname for v in validate):
                    continue
                try:
                    good = httpx.get(sink_base + path.replace("{" + params[0] + "}", m["value"]), timeout=5)
                    bad = httpx.get(sink_base + path.replace("{" + params[0] + "}", "PATCHWORK-NOPE"), timeout=5)
                except httpx.HTTPError:
                    continue
                if good.status_code == 200 and bad.status_code == 404:
                    validate.append({"field": fname, "rule": "exists",
                                     "check": {"method": "GET", "path": path.replace("{" + params[0] + "}", "{" + fname + "}")}})
        verify = None
        get_op = doc.get("paths", {}).get(sink["path"], {}).get("get")
        if get_op:
            for p in get_op.get("parameters", []):
                if p.get("in") == "query" and p["name"] in body and "from" in body[p["name"]]:
                    verify = {"method": "GET", "path": sink["path"], "params": {p["name"]: "{" + body[p["name"]]["from"] + "}"},
                              "expect_count": 1}
                    break
        key = [body[k]["from"] for k in body if k in ("reference", "ref", "id", "order_id") and "from" in body[k]] \
            or [d["from"] for d in body.values() if "from" in d]
        assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "inferred",
                            "text": f"{', '.join(key)} identifies a record; resends are duplicates"})
        assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "inferred",
                            "text": "Messages the parsers can't read are quarantined for review, not dropped"})
        source = {"kind": "api", "base_url": src["base_url"],
                  "list": {"method": src["list"]["method"], "path": src["list"]["path"]},
                  "record_id": src["record_id"], "text_field": src["text_field"]}
        if "received_at" in record:
            source["list"]["params"] = {"since": "{cursor}"}
            source["cursor_field"] = "received_at"
        spec = {
            "spec_version": 1, "name": ctx.name, "intent": rec.get("intent") or c.get("intent", ""),
            "source": source,
            "extract": {"route_by": route_by or src["record_id"],
                        "parsers": [{"id": pid, "match": {route_by: route_val} if route_by else {}, "fields": fields}]},
            "validate": validate, "dedupe": {"key": key},
            "sink": {"kind": "api", "base_url": sink["base_url"], "staging_base_url": _port_plus_one(sink["base_url"]),
                     "call": {"method": sink["method"], "path": sink["path"]}, "body": body,
                     **({"verify": verify} if verify else {})},
            "on_error": "quarantine", "assumptions": assumptions,
        }
        errors = validate_spec(_ydump(spec))
        ctx.spec_path.write_text(_ydump(spec, sort_keys=False, width=200))
        examples = [{"name": f"recorded_{re.sub(r'[^a-z0-9]+', '_', str(record.get(src['record_id'])).lower())}",
                     "record": record, "expect": {"body": sink["body"]}}]
        (ctx.wd / "examples.yaml").write_text(_ydump(examples, sort_keys=False, width=200))
        ctx.svc.emit(ctx.t, "artifact", kind="spec", name=ctx.name, version=None, path=str(ctx.spec_path))
        return (f"wrote spec.yaml (parser {pid}, {len(fields)} fields, {len(validate)} rules, dedupe {key}"
                f"{', verify' if verify else ''}) and examples.yaml (1 recorded example). "
                + ("valid" if not errors else "INVALID: " + "; ".join(errors)))

    def validate_spec_tool() -> str:
        """Validate the current spec.yaml (closed vocabulary). Returns 'valid' or the errors to fix."""
        if not ctx.spec_path.exists():
            return "ERROR: no spec.yaml yet"
        errors = ctx.validate_spec_text(ctx.spec_path.read_text())
        return "valid" if not errors else "INVALID:\n" + "\n".join(f"- {e}" for e in errors)

    def propose_spec_patch(patch: list[dict], reason: str = "") -> str:
        """Apply an RFC 6902 JSON Patch to spec.yaml (the spec only; runtime code is regenerated by the
        compiler). Paths look like /sink/body/sku or /extract/parsers/- . The patch is applied only if the
        resulting spec is valid; otherwise nothing is written and the errors are returned."""
        if not ctx.spec_path.exists():
            return "REFUSED: no spec.yaml to patch"
        old = ctx.spec_dict()
        fixed = ("/name", "/sink/base_url", "/source/base_url", "/sink/url", "/sink/kind", "/source/kind",
                 "/sink/base_id", "/sink/table", "/sink/auth", "/source/auth")
        if any(str(op.get(k, "")).startswith(fixed) for op in patch for k in ("path", "from")):
            return ("REFUSED: name, kinds, base/form URLs, Airtable base/table and credentials are fixed; patch the "
                    "mapping, parsers, rules or assumptions")
        try:
            new = jsonpatch.apply_patch(old, patch)
        except (jsonpatch.JsonPatchException, jsonpatch.JsonPointerException, TypeError, KeyError) as e:
            return f"REFUSED: patch does not apply: {e}"
        errors = ctx.validate_spec_text(_ydump(new))
        if errors:
            return "REFUSED (spec unchanged):\n" + "\n".join(f"- {e}" for e in errors)
        ctx.spec_path.write_text(_ydump(new, sort_keys=False, width=200))
        ctx.svc.emit(ctx.t, "artifact", kind="spec", name=ctx.name, version=None, path=str(ctx.spec_path))
        return f"applied {len(patch)} operation(s); spec.yaml is valid"

    def add_test_case(record_id: str, expect_body: dict | None = None, expect_quarantine: str = "",
                      missing: list[str] | None = None) -> str:
        """Add a golden example to examples.yaml from a real source record: either the exact sink body it
        must produce (expect_body) or the quarantine code it must end in (PARSE_NO_MATCH,
        VALIDATION_FAILED, NOT_FOUND). `missing` lists ids the existence check should treat as unknown."""
        rec = next((r for r in ctx.samples if str(r.get("id")) == record_id), None)
        page_mode = ctx.mode == "learn" or (ctx.spec_path.exists() and is_page_integration(ctx.spec_dict()))
        if rec is None and page_mode:
            try:
                rec = ctx.get_page_record(record_id)
            except KeyError as e:
                return f"ERROR: page {record_id} not found: {e}"
        if rec is None:
            try:
                path = ctx.spec_dict()["source"]["list"]["path"] if ctx.spec_path.exists() else "/api/messages"
                resp = httpx.get(f"{ctx.source_base()}{path}/{record_id}", timeout=10,
                                 headers=ctx.auth_headers("source"))
                resp.raise_for_status()
                rec = resp.json()
            except httpx.HTTPError as e:
                return f"ERROR: record {record_id} not found: {e}"
        expect = {"body": expect_body} if expect_body is not None else {"quarantine": expect_quarantine}
        prefix = (rec.get("sender_domain") or rec.get("site") or "rec").split(".")[0]
        name = re.sub(r"[^a-z0-9]+", "_", f"{prefix}_{record_id}".lower())
        ex = {"name": name, "record": rec, "expect": expect, **({"missing": missing} if missing else {})}
        try:
            Example.parse(ex)
        except CompileError as e:
            return f"REFUSED: {e}"
        path = ctx.wd / "examples.yaml"
        examples = [e for e in (_yload(path.read_text()) if path.exists() else []) or [] if e["name"] != name]
        examples.append(ex)
        path.write_text(_ydump(examples, sort_keys=False, width=200))
        return f"added example {name} ({'body' if expect_body is not None else expect_quarantine}); {len(examples)} examples total"

    def compile_spec() -> str:
        """Compile spec.yaml (+ examples.yaml, transforms.py) into the next immutable version and run its
        full generated test suite. Refuses invalid specs. Never deploys."""
        if ctx.stopped:
            return "REFUSED: the user asked to stop this repair"
        if not ctx.spec_path.exists():
            return "REFUSED: no spec.yaml"
        errors = ctx.validate_spec_text(ctx.spec_path.read_text())
        if errors:
            return "REFUSED: spec is invalid, fix it first:\n" + "\n".join(f"- {e}" for e in errors)
        if ctx.mode == "repair" and ctx.failed_attempts >= MAX_REPAIR_ATTEMPTS:
            answer = ctx.interrupt(
                "ask_user", question=f"I couldn't get the tests green after {MAX_REPAIR_ATTEMPTS} repair attempts. "
                                     "How should I proceed?",
                options=["Stop the repair; I'll take it from here", "Try 3 more times"])
            if "more" not in str(answer.get("answer", "")).lower():
                ctx.stopped = True
                return "REFUSED: user stopped the repair after 3 failed attempts. Stop now and report."
            ctx.failed_attempts = 0
        ctx.compile_attempts += 1
        try:
            built = ctx.compile_and_test(ctx.spec_path)
        except (CompileError, SpecError) as e:
            ctx.failed_attempts += 1
            return f"ERROR: compile failed: {e}"
        ctx.last_version = built
        ctx.svc.emit(ctx.t, "artifact", kind="package", name=ctx.name, version=built["version"], path=built["path"])
        if not built["tests_passed"]:
            ctx.failed_attempts += 1
            tail = "\n".join(built["tests_summary"].splitlines()[-25:])
            left = MAX_REPAIR_ATTEMPTS - ctx.failed_attempts if ctx.mode == "repair" else None
            return (f"FAILED: v{built['version']} compiled but tests failed"
                    + (f" ({left} repair attempts left)" if left is not None else "") + f":\n{tail}")
        extra = f"; contract warnings: {built['contract_errors']}" if built["contract_errors"] else ""
        return f"compiled v{built['version']}: tests passed ({built['tests_summary']}){extra}"

    def run_tests(version: int) -> str:
        """Re-run the full generated test suite of a compiled version."""
        passed, summary = ops.run_tests(ctx.name, int(version))
        return (f"v{version}: passed ({summary})" if passed
                else f"FAILED: v{version}:\n" + "\n".join(summary.splitlines()[-25:]))

    def dry_run(limit: int = 10) -> str:
        """Run the latest passing version against the STAGING sink only, on `limit` real records."""
        store = Store()
        passing = [v for v in store.versions(ctx.name) if v["tests_passed"]]
        if not passing:
            return "REFUSED: no compiled version has passing tests yet"
        v = passing[-1]["version"]
        vdir = workspace_dir() / "integrations" / ctx.name / f"v{v}"
        cfg = _yload((vdir / "config.yaml").read_text())
        # forms fill but never submit on dry runs (V5); Airtable validates against the table, never POSTs (V14)
        is_form = cfg["sink"].get("kind") in LABEL_KEYED_SINKS
        staging = (os.environ.get("PATCHWORK_STAGING_BASE_URL") or cfg["sink"].get("staging_base_url") or "").rstrip("/")
        live = (os.environ.get("PATCHWORK_SINK_BASE_URL") or cfg["sink"].get("base_url") or "").rstrip("/")
        if not is_form and (not staging or staging == live):
            return "REFUSED: no separate staging sink configured; agents never write to the live sink"
        try:
            s = ops.run_sandboxed(ctx.name, version=str(v), dry_run=True, limit=max(1, min(int(limit), 25)), timeout=120)
        except Exception as e:  # noqa: BLE001
            return f"ERROR: dry run unavailable: {e}"
        ok = s.get("status") == "completed"
        return (("" if ok else "FAILED: ") + f"dry run of v{v} on staging: {s.get('status')} {s.get('counts')}"
                + (f" ({s.get('message')})" if s.get("message") else ""))

