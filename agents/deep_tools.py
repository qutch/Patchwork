_FIELD_ALIASES = {"job title": "title", "title": "title", "position": "title", "role": "title",
                  "company": "company", "company name": "company", "employer": "company", "organization": "company"}


def _field_name(label: str) -> str:
    key = " ".join(label.lower().replace("*", "").split())
    return _FIELD_ALIASES.get(key) or (re.sub(r"[^a-z0-9]+", "_", key).strip("_") or "field")


def site_parser_id(site: str) -> str:
    """jobs.lever.co -> lever, job-boards.greenhouse.io -> greenhouse, careers.airbnb.com -> airbnb."""
    parts = [p for p in (site or "").lower().split(".") if p]
    name = parts[-2] if len(parts) >= 2 else (parts[0] if parts else "page")
    name = re.sub(r"[^a-z0-9]+", "_", name).strip("_") or "page"
    return name if name[0].isalpha() else f"p_{name}"


def _extractor_from_mapping(m: dict) -> dict | None:
    if m.get("kind") == "css" and m.get("css"):
        f = {"css": m["css"]}
    elif m.get("kind") == "jsonld" and m.get("jsonld"):
        f = {"jsonld": m["jsonld"], **({"jsonld_type": m["jsonld_type"]} if m.get("jsonld_type") else {})}
    else:  # copied text without a selector: fall back to a recorded alternative
        alt = next((a for a in m.get("alternatives") or [] if isinstance(a, dict) and (a.get("css") or a.get("jsonld"))), None)
        if alt is None:
            return None
        f = {k: alt[k] for k in ("css", "attr", "jsonld", "jsonld_type", "regex") if alt.get(k)}
        return f
    for k in ("attr", "regex"):
        if m.get(k):
            f[k] = m[k]
    return f


def draft_page_spec(c: dict, *, name: str, thread_id: str, html: str,
                    airtable: dict | None = None) -> tuple[dict, list[dict], list[str]]:
    """V11 page->form candidates -> a V7/V5 spec with one taught parser, plus one golden example built from
    the snapshot (expected values are the recorded ones, independent of the parser). Returns
    (spec, examples, problems).

    `airtable` (V14 retarget): {base_id, table, credential, fields: {form label: Airtable field name or None},
    contract}: the sink becomes that table, each label keyed by its field name; a None drops the label (a
    person chose to skip it). Golden values are typed per the table's fields."""
    src, sink = c["source"], c["sink"]
    site = src.get("site") or ""
    fields, form_fields, assumptions, problems = {}, {}, [], []
    record_values: dict[str, str] = {}
    by_label = {m["dest_field"]: m for m in c.get("mappings") or []}
    labels = list(sink.get("labels") or by_label)
    for label in labels:
        m = by_label.get(label)
        if m is None:
            continue
        kind = m.get("kind")
        if kind == "record" and str(m.get("from", "")).startswith("record."):
            form_fields[label] = {"from": m["from"]}
            record_values[label] = m["from"]
            assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "observed",
                                "text": f"{label} comes from the page record ({m['from']})"})
        elif kind == "const":
            form_fields[label] = {"const": m["value"]}
            assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "inferred",
                                "text": f"{label} is always {m['value']!r} (typed during the recording)"})
        else:
            f = _extractor_from_mapping(m)
            if f is None:
                problems.append(f"{label}: no selector or alternative to read it from the page")
                continue
            fname = _field_name(label)
            fields[fname] = f
            form_fields[label] = {"from": fname}
            assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "observed",
                                "text": f"{label} is read from the page ({learn.extractor_label(f)})"})
    for u in c.get("unexplained") or []:
        form_fields[u["dest_field"]] = {"const": u["value"]}
        assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "inferred",
                            "text": f"{u['dest_field']} is always {u['value']!r} (not found on the page)"})
    assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "inferred",
                        "text": "the posting's canonical URL identifies it; pressing the hotkey twice is a duplicate"})
    parser = {"id": site_parser_id(site), "match": {"site": site},
              "origin": {"kind": "taught", "at": now(), "thread_id": thread_id, "approved_by": None},
              "fields": fields}
    spec = {
        "spec_version": 1, "name": name, "intent": c.get("intent") or "",
        "source": {"kind": "api", "base_url": CONTROL_SOURCE,
                   "list": {"method": "GET", "path": "/api/pages", "params": {"since": "{cursor}"}},
                   "record_id": "id", "text_field": "text", "html_field": "html", "cursor_field": "seq"},
        "extract": {"route_by": "site", "parsers": [parser]},
        "validate": [{"field": f, "rule": "required"} for f in fields],
        "dedupe": {"key": ["record.canonical_url"]},
        "sink": {"kind": "form", "url": sink["url"], "fields": form_fields, "submit": sink.get("submit") or "Submit",
                 **({"verify": {"confirmation_text": sink["confirmation_text"]}} if sink.get("confirmation_text") else {})},
        "on_error": "quarantine", "assumptions": assumptions,
    }
    if airtable is not None:
        names = airtable["fields"]
        form_fields = {names[lab]: vs for lab, vs in form_fields.items() if names.get(lab)}
        spec["sink"] = {"kind": "airtable", "base_id": airtable["base_id"], "table": airtable["table"],
                        "auth": {"scheme": "bearer", "credential": airtable["credential"]},
                        "fields": form_fields, "typecast": False, "verify": {"read_back": True}}
        skipped = [lab for lab, n in names.items() if not n]
        for lab, n in names.items():
            if n and n != lab:
                assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "confirmed",
                                    "text": f"the form question {lab!r} goes to the Airtable field {n!r}"})
        for lab in skipped:
            assumptions.append({"id": f"a{len(assumptions) + 1}", "status": "confirmed",
                                "text": f"the form question {lab!r} is not sent: the table has no field for it"})
        by_label = {names[lab]: m for lab, m in by_label.items() if names.get(lab)}
        record_values = {names[lab]: ref for lab, ref in record_values.items() if names.get(lab)}
    date = next((by_label[lab]["value"] for lab, ref in record_values.items() if ref == "record.captured_date"), None)
    rec = learn.make_page_record(src["url"], html, seq=1, captured_at=f"{date}T12:00:00.000+00:00" if date else None)
    body = {}
    for label, vs in form_fields.items():
        if "const" in vs:
            body[label] = str(vs["const"])
        elif vs["from"].startswith("record."):
            body[label] = str(rec[vs["from"].removeprefix("record.")])
        else:
            body[label] = str(by_label[label]["value"])
    if airtable is not None and airtable.get("contract"):
        from runner.airtable import convert_body
        try:  # what build_body produces: values typed per the table's fields (V14)
            body = convert_body(airtable["contract"], body, drop_empty=False)
        except Quarantine as q:
            problems.append(f"golden example: {q.detail}")
    examples = [{"name": f"taught_{parser['id']}_1", "record": rec, "expect": {"body": body}}]
    return spec, examples, problems


def summarize_recording(rec: dict) -> str:
    lines = [f"intent: {rec.get('intent')}", f"allowlist: {rec.get('allowlist')}", f"events: {len(rec['events'])}"]
    for e in rec["events"]:
        typ = e.get("type")
        if typ == "framenavigated":
            lines.append(f"- navigate {e.get('url')} ({e.get('title')})")
        elif typ == "net":
            body = e.get("req") if e.get("method") in ("POST", "PUT", "PATCH") else None
            resp = e.get("resp")
            n = f"{len(resp)} items" if isinstance(resp, list) else "1 object"
            lines.append(f"- {e.get('method')} {e.get('url')} -> {e.get('status')}"
                         + (f" body={json.dumps(body)}" if body is not None else f" ({n})"))
        else:
            el = e.get("el") or {}
            label = el.get("label") or el.get("name") or el.get("testid") or el.get("css")
            val = e.get("value", e.get("text"))
            lines.append(f"- {typ} on {label!r}" + (f" value={val!r}" if val is not None else "")
                         + (f" (near {el.get('nearby')!r})" if el.get("nearby") else ""))
    return "\n".join(lines)


def summarize_openapi(doc: dict) -> str:
    out = []
    for path, ops_ in sorted(doc.get("paths", {}).items()):
        for method, op in ops_.items():
            line = f"{method.upper()} {path}"
            params = [p["name"] for p in op.get("parameters", []) if p.get("in") == "query"]
            if params:
                line += f" query={params}"
            schema = request_schema(doc, method, path)
            if schema:
                line += " body=" + json.dumps(_flatten_schema(doc, schema))
            out.append(line)
    return "\n".join(out)


def _resolve(doc: dict, schema: dict) -> dict:
    while isinstance(schema, dict) and "$ref" in schema:
        node: Any = doc
        for part in schema["$ref"][2:].split("/"):
            node = node.get(part, {})
        schema = node
    return schema or {}


def _flatten_schema(doc: dict, schema: dict) -> dict:
    schema = _resolve(doc, schema)
    props = {}
    for k, v in schema.get("properties", {}).items():
        v = _resolve(doc, v)
        desc = v.get("type", "any")
        if "enum" in v:
            desc += f" enum={v['enum']}"
        if "exclusiveMinimum" in v:
            desc += f" >{v['exclusiveMinimum']:g}"
        props[k] = desc
    return {"properties": props, "required": schema.get("required", []),
            **({"additionalProperties": False} if schema.get("additionalProperties") is False else {})}


def diff_request_schemas(old_doc: dict, new_doc: dict, method: str, path: str,
                         body_map: dict[str, dict] | None = None) -> dict:
    """Compare the request body schema of one operation and pair removed/added properties into
    likely renames: by name similarity first, then by matching the extracted field that fed the old
    property, then by unique type (enum-ness must agree)."""
    old = _flatten_schema(old_doc, request_schema(old_doc, method, path) or {})
    new = _flatten_schema(new_doc, request_schema(new_doc, method, path) or {})
    removed = {k: v for k, v in old["properties"].items() if k not in new["properties"]}
    added = {k: v for k, v in new["properties"].items() if k not in old["properties"]}
    body_map = body_map or {}
    renames: dict[str, str] = {}

    def base_type(d: str) -> tuple[str, bool]:
        return d.split()[0], "enum=" in d

    for r in list(removed):
        best = max(added, key=lambda a: difflib.SequenceMatcher(None, r, a).ratio(), default=None)
        if best and best not in renames.values() and (
                difflib.SequenceMatcher(None, r, best).ratio() >= 0.6 or best.startswith(r) or r.startswith(best)) \
                and base_type(removed[r]) == base_type(added[best]):
            renames[r] = best
    for r in removed:
        if r in renames:
            continue
        src = (body_map.get(r) or {}).get("from")
        if src and src in added and src not in renames.values():
            renames[r] = src
    for r in removed:
        if r in renames:
            continue
        same = [a for a in added if a not in renames.values() and base_type(added[a]) == base_type(removed[r])]
        if len(same) == 1:
            renames[r] = same[0]
    new_required = {a: added[a] for a in added if a not in renames.values() and a in new["required"]}
    return {"operation": f"{method} {path}", "removed": removed, "added": added,
            "likely_renames": renames, "new_required_unmapped": new_required,
            "old_required": old["required"], "new_required": new["required"]}


# ---- parsing against real samples ------------------------------------------------------------

def run_parser(parser: dict, text_field: str, record: dict, html_field: str | None = None) -> dict:
    fields = {}
    text = record.get(text_field) or ""
    for fname, f in parser["fields"].items():
        where = f"{parser.get('id', 'parser')}.{fname}"
        if f.get("css") is not None or f.get("jsonld") is not None:  # page extractors (V3), same helpers as runs
            fields[fname] = learn.extract_field(f, record, where, html_field or "html", text_field)
            continue
        if f.get("combine") == "product" and f.get("regex") is not None:
            fields[fname] = extract_product(text, re.compile(f["regex"]), f.get("cast", "int"), where)
            continue
        if f.get("regex") is not None:
            raw = extract_regex(text, re.compile(f["regex"]), where)
        elif f.get("between") is not None:
            raw = extract_between(text, f["between"][0], f["between"][1], where)
        elif f.get("json_path") is not None:
            raw = extract_json_path(record, f["json_path"], where)
        else:
            raise Quarantine("PARSE_NO_MATCH", f"{where}: no extract method")
        fields[fname] = cast(raw, f.get("cast", "str"), where)
    return fields


def _matches(match: dict, record: dict) -> bool:
    return match_rank({k: str(v) for k, v in (match or {}).items()}, record) > 0


def eval_value(vs: dict, fields: dict, record: dict) -> Any:
    """Evaluate a spec value source the way generated code does (used to migrate golden bodies)."""
    def ref(r: str) -> Any:
        return record[r.removeprefix("record.")] if r.startswith("record.") else fields[r]
    if "template" in vs:
        return re.sub(r"\{([A-Za-z_][A-Za-z0-9_.]*)\}", lambda m: str(ref(m.group(1))), vs["template"])
    if vs.get("transform"):
        name = vs["transform"]
        if name.startswith("custom:"):
            raise ValueError("custom transforms cannot be evaluated here")
        return getattr(T, name)(ref(vs["from"]), **(vs.get("args") or {}))
    if "from" in vs:
        return ref(vs["from"])
    return vs.get("const")


def lint_spec(spec: dict) -> list[str]:
    """Checks the schema can't express: lookup tables must cover every routed value, and the staging
    sink must never be the live sink."""
    problems = []
    sink = spec.get("sink", {})
    if sink.get("staging_base_url") and sink.get("staging_base_url", "").rstrip("/") == sink.get("base_url", "").rstrip("/"):
        problems.append("sink.staging_base_url must not equal sink.base_url (agents never write to live)")
    route_by = spec.get("extract", {}).get("route_by")
    routed = {str(p.get("match", {}).get(route_by)) for p in spec.get("extract", {}).get("parsers", [])
              if p.get("match", {}).get(route_by) is not None}
    for key, vs in (sink_values(spec) or {}).items():
        if vs.get("transform") == "lookup" and vs.get("from") == f"record.{route_by}":
            table = (vs.get("args") or {}).get("table") or {}
            missing = sorted(routed - set(map(str, table)))
            if missing and (vs.get("args") or {}).get("default") is None:
                problems.append(f"sink.body.{key}: lookup table keys {sorted(table)} do not cover routed "
                                f"{route_by} values {missing}; use the exact values, e.g. {sorted(routed)}")
    return problems


def _ptr(key: str) -> str:
    """JSON Pointer escaping for one key (form labels may contain '/' or '~')."""
    return key.replace("~", "~0").replace("/", "~1")


def _short(obj: Any, n: int = 900) -> str:
    s = obj if isinstance(obj, str) else json.dumps(obj, default=str)
    return s if len(s) <= n else s[:n] + f"… (+{len(s) - n} chars)"


def _port_plus_one(url: str) -> str:
    p = urlparse(url)
    if p.port:
        return urlunparse(p._replace(netloc=f"{p.hostname}:{p.port + 1}"))
    return url


