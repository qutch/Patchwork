"""Build V1 page records from fixtures/pages/ (test helper and the generator of examples.yaml).

    python -m fixtures.jobs.pages      # rewrites fixtures/jobs/examples.yaml

Example records carry a slimmed copy of the page (scripts other than JSON-LD, styles, SVGs and
comments removed) so golden.json stays small; visible text, JSON-LD and every reader's target are
unchanged by the slimming (checked below and in tests/engine/test_spec_v2.py).
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

import yaml

from runner.html import canonical_url, css_first, normalize_ws, site_of, visible_text

REPO = Path(__file__).resolve().parents[2]
PAGES = REPO / "fixtures" / "pages"
INDEX: list[dict[str, Any]] = json.loads((PAGES / "index.json").read_text())
CAPTURED_DATE = "2026-11-14"
EMAIL = "demo@example.com"
EXAMPLE_PLATFORMS = ("lever", "greenhouse", "ashby")

_SCRIPT = re.compile(r"<script\b(?![^>]*application/ld\+json)[^>]*>.*?</script\s*>", re.S | re.I)
_STYLE = re.compile(r"<style\b[^>]*>.*?</style\s*>", re.S | re.I)
_SVG = re.compile(r"<svg\b[^>]*>.*?</svg\s*>", re.S | re.I)
_COMMENT = re.compile(r"<!--.*?-->", re.S)


def slim(html: str) -> str:
    for pat in (_SCRIPT, _STYLE, _SVG, _COMMENT):
        html = pat.sub("", html)
    return html


def page_record(seq: int, url: str, html: str, *, captured_at: str, captured_date: str = CAPTURED_DATE,
                title: str | None = None) -> dict[str, Any]:
    """A page record shaped exactly as contracts V1."""
    return {
        "id": f"pg-{seq:06d}", "seq": seq, "url": url,
        "canonical_url": canonical_url(url, html), "site": site_of(url),
        "title": title if title is not None else normalize_ws(css_first(html, "title") or ""),
        "html": html, "text": visible_text(html),
        "captured_at": captured_at, "captured_date": captured_date,
    }


def fixture_records(*, slimmed: bool = False) -> list[dict[str, Any]]:
    """All 8 fixture pages as page records, seq 1..8 in index order."""
    out = []
    for seq, entry in enumerate(INDEX, start=1):
        html = (PAGES / entry["file"]).read_text()
        rec = page_record(seq, entry["url"], html, captured_at=entry["fetched_at"])
        if slimmed:
            rec["html"] = slim(html)
        out.append(rec)
    return out


def expected_body(record: dict[str, Any], entry: dict[str, Any]) -> dict[str, str]:
    return {"Email": EMAIL, "Job Title": entry["expected"]["title"], "Company": entry["expected"]["company"],
            "Link": record["canonical_url"], "Date Applied": record["captured_date"]}


def build_examples() -> list[dict[str, Any]]:
    examples = []
    for entry, full, small in zip(INDEX, fixture_records(), fixture_records(slimmed=True)):
        if entry["platform"] not in EXAMPLE_PLATFORMS:
            continue
        assert small["text"] == full["text"] or visible_text(small["html"]) == full["text"], entry["file"]
        small["text"] = visible_text(small["html"])
        examples.append({"name": entry["file"].removesuffix(".html"), "record": small,
                         "expect": {"body": expected_body(small, entry)}})
    return examples


if __name__ == "__main__":
    out = REPO / "fixtures" / "jobs" / "examples.yaml"
    out.write_text("# Generated by `python -m fixtures.jobs.pages` from fixtures/pages/. Do not edit.\n"
                   + yaml.safe_dump(build_examples(), sort_keys=False, allow_unicode=True, width=1 << 20))
    print(f"wrote {out} ({out.stat().st_size} bytes)")
